"""R13 IE routes (prefix /api/v1/intel/governance). One API per engine, each with an export.

  POST /inspection                 {request, sample[]} -> evidence pack with coverage check
  POST /inspection/export?fmt=     docx | xlsx  (house style)
  GET  /inspection/samples         R14 G (K14): three sample requests and the pack sections (empty state)
  GET  /exceptions                 ?type=&limit= -> exception intelligence
  GET  /rm-track                   ?group=rm|branch -> RM track record
  GET  /doa                        DoA calibration and proposed redesign
  GET  /{engine}/export            Excel of exceptions | rm-track | doa
  GET  /health

Mounted on the Deal Desk service (backend/dealdesk/api.py, "# R13 routers") and the Admin service
(backend/admin/api.py), so both tools menus call it on their own origin. Each answer carries a trace id.
"""
from __future__ import annotations

from typing import Any

from fastapi import APIRouter, HTTPException, Query, Request
from fastapi.responses import Response
from pydantic import BaseModel, Field

from . import common as C
from . import doa, exceptions, export, inspection, rm_track

PREFIX = "/api/v1/intel/governance"
router = APIRouter(prefix=PREFIX, tags=["intel-governance"])
DOCX = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
XLSX = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"


class InspectionAsk(BaseModel):
    request: str = Field(default="", max_length=4000)
    sample: list[str] = Field(default_factory=list, max_length=200)


def _user(request: Request) -> str:
    try:
        from backend.identity_v5.client import current_user
        return (current_user(request) or {}).get("username", "")
    except Exception:  # noqa: BLE001 - answers without the Core service
        return ""


def _by(request: Request) -> str:
    """The export's "Generated by": the signed-in user's name and role (house style), else the username."""
    try:
        from backend.house_style import generated_by
        return generated_by(request) or _user(request)
    except Exception:  # noqa: BLE001
        return _user(request)


def _traced(kind: str, inputs: dict[str, Any], out: dict[str, Any], user: str) -> dict[str, Any]:
    try:
        from backend.dealdesk import params, trace
        tid = trace.record(kind, inputs, {"lines": out.get("lines")}, params.versions(), "intel-governance-r13", user)
    except Exception:  # noqa: BLE001 - a trace never breaks an answer
        tid = None
    return {"trace_id": tid, **out}


def _file(data: bytes, name: str, mime: str) -> Response:
    return Response(content=data, media_type=mime, headers={"Content-Disposition": f'attachment; filename="{name}"'})


@router.get("/health")
def health() -> dict[str, Any]:
    d = C.decisions()
    return {"ok": True, "decisions": int(len(d)), "steps": int(len(C.steps())), "exceptions": int(len(C.exceptions()))}


@router.post("/inspection")
def inspection_pack(body: InspectionAsk, request: Request) -> dict[str, Any]:
    if not body.request.strip() and not body.sample:
        raise HTTPException(422, "Give the request text, a sample list, or both.")
    return _traced("gov_inspection", body.model_dump(), inspection.respond(body.request, body.sample), _user(request))


@router.get("/inspection/samples")
def inspection_samples() -> dict[str, Any]:
    """R14 G (K14): what the responder is for, three clickable sample requests and the sections of the pack."""
    return {"samples": inspection.SAMPLES, "sections": inspection.PACK_SECTIONS}


@router.post("/inspection/export")
def inspection_export(body: InspectionAsk, request: Request, fmt: str = Query(default="docx", pattern="^(docx|xlsx)$")) -> Response:
    if not body.request.strip() and not body.sample:
        raise HTTPException(422, "Give the request text, a sample list, or both.")
    pack = inspection.respond(body.request, body.sample)
    user = _by(request)
    if fmt == "xlsx":
        return _file(export.inspection_xlsx(pack, user), f"{pack['pack_id']}.xlsx", XLSX)
    return _file(export.inspection_docx(pack, user), f"{pack['pack_id']}.docx", DOCX)


@router.get("/exceptions")
def exception_intel(request: Request, type: str = Query(default=""), limit: int = Query(default=60, ge=1, le=500)) -> dict[str, Any]:
    if type and type not in exceptions.TYPE_LABEL:
        raise HTTPException(404, f"Unknown exception type {type!r}.")
    return _traced("gov_exceptions", {"type": type, "limit": limit}, exceptions.analyse(type or None, limit), _user(request))


@router.get("/rm-track")
def rm_track_record(request: Request, group: str = Query(default="rm", pattern="^(rm|branch)$"),
                    limit: int = Query(default=100, ge=1, le=500)) -> dict[str, Any]:
    return _traced("gov_rm_track", {"group": group}, rm_track.analyse(group, limit), _user(request))


@router.get("/doa")
def doa_calibration(request: Request) -> dict[str, Any]:
    return _traced("gov_doa", {}, doa.analyse(), _user(request))


@router.get("/{engine}/export")
def engine_export(engine: str, request: Request, group: str = Query(default="rm", pattern="^(rm|branch)$")) -> Response:
    user = _by(request)
    if engine == "exceptions":
        out, kind = exceptions.analyse(None, 500), "exceptions"
    elif engine == "rm-track":
        out, kind = rm_track.analyse(group, 500), "rm"
    elif engine == "doa":
        out, kind = doa.analyse(), "doa"
    else:
        raise HTTPException(404, "Unknown engine.")
    if not out.get("available"):
        raise HTTPException(409, out["lines"][0])
    return _file(export.engine_xlsx(kind, out, user), f"governance-{engine}.xlsx", XLSX)
