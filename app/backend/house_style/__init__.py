BOOKS = {"corporate": "Corporate book", "retail": "Retail book", "both": "Corporate and retail books"}


@dataclass
class Meta:
    """The header block: what the file is, which book and period, who generated it and when."""

    title: str
    book: str = ""                 # corporate | retail | both | free text
    period: str = ""
    subject: str = ""              # one line of scope, e.g. "Construction · Stage 2"
    generated_by: str = ""         # the signed-in user's name (and role)
    generated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    reference: str = ""
    classification: str = "INTERNAL"

    @property
    def book_label(self) -> str:
        return BOOKS.get(self.book, self.book)

    @property
    def when(self) -> str:
        return self.generated_at.strftime("%d %b %Y %H:%M UTC")

    def scope_line(self) -> str:
        return " · ".join(x for x in (self.book_label, self.period and f"Period {self.period}", self.subject) if x)

    def generated_line(self) -> str:
        return f"Generated by {self.generated_by or 'CreditProbe'} on {self.when}" + (f" · Ref. {self.reference}" if self.reference else "")

    def lines(self) -> list[str]:
        """Rows 1-4 of every sheet."""
        return ["CREDITPROBE", self.title, self.scope_line(), self.generated_line()]

    def about_items(self) -> list[tuple[str, Any]]:
        return [("Title", self.title), ("Book", self.book_label or "—"), ("Period", self.period or "—"),
                *([("Scope", self.subject)] if self.subject else []),
                ("Generated by", self.generated_by or "CreditProbe"), ("Generated", self.when),
                *([("Reference", self.reference)] if self.reference else []),
                ("Classification", self.classification)]


def user_label(user: dict[str, Any] | None) -> str:
    """'Anne (Administrator)' from an identity_v5 user record; '' when nobody is signed in."""
    if not user:
        return ""
    name = user.get("name") or user.get("username") or ""
    role = user.get("role_label") or user.get("title") or user.get("role") or ""
    return f"{name} ({role})" if name and role else name


def generated_by(request: Any) -> str:
    """The signed-in user behind an API request, for the header block. Never fails an export."""
    try:
        from backend.identity_v5 import client
        return user_label(client.current_user(request))
    except Exception:  # noqa: BLE001 - an export never fails because the directory is unreachable
        return ""


# ------------------------------------------------------------------ adapters for callers written before the contract
def word_document(title: str, subtitle: str = "", meta: list[tuple[str, str]] | None = None, kind: str = "Report",
                  generated_by: str = "", **_: Any) -> Any:
    """A house-style Word document from (label, value) details (Playbook's adapter, backend/playbook_v5/house.py)."""
    from backend.house_style import docx as hd
    details = [(str(k), str(v)) for k, v in (meta or []) if v not in (None, "")]
    take = {k.lower(): v for k, v in details}
    book = take.pop("book", "")
    period = take.pop("period", "")
    rest = [(k, v) for k, v in details if k.lower() not in ("book", "period")]
    m = Meta(title, book=book.lower() if book.lower() in BOOKS else book, period=period, generated_by=generated_by)
    return hd.document(m, kind=kind, subtitle=subtitle, details=rest)


def word_table(doc: Any, header: list[str], rows: list[list[Any]], numeric: list[bool] | None = None, **_: Any) -> Any:
    """A house-style Word table where the caller passes which columns are numeric."""
    from backend.house_style import docx as hd
    right = None
    if numeric and any(numeric):
        right = next(i for i, n in enumerate(numeric) if n) if all(numeric[next(i for i, n in enumerate(numeric) if n):]) else None
    t = hd.table(doc, header, rows, right_from=right)
    if numeric and right is None:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        for row in t.rows:
            for i, cell in enumerate(row.cells):
                if i < len(numeric) and numeric[i]:
                    for par in cell.paragraphs:
                        par.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    return t


