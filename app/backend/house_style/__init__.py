"""The CreditProbe house style: one look for every .xlsx and .docx the product writes (PLAN_R3 S3-1).

Every export calls this package; no module styles a file itself. Three writers share one set of
decisions (brand colours, the header block, number formats):

  backend.house_style.xlsx    openpyxl workbooks: styled tables, About sheet, header block
  backend.house_style.stream  a fast stdlib writer for large row exports, same look
  backend.house_style.docx    Word documents: cover page, headings, page numbers, table style
  backend.house_style.check   the assertions the tests and the UAT sweep run on every export

The contract other sessions code against is docs/v5/HOUSE_STYLE.md.
"""
