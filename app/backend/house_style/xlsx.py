"""House-style workbooks with openpyxl.

    from backend.house_style import Meta, xlsx as hx
    meta = Meta("Borrower 360 · CB01312", book="corporate", period="2026Q2", generated_by=hx_user)
    wb = hx.workbook(meta)
    hx.table_sheet(wb, "Facilities", meta, [hx.Col("facility_id", "Facility"), hx.Col("ead", "EAD", "sar_mn")], rows)
    hx.about_sheet(wb, meta, [("Rule set", "gw-ews-1.2.0")])
    data = hx.to_bytes(wb)

Every sheet opens on the header block (rows 1-4: brand line, title, book and period, generated by and
when). A table sheet has its header on HEADER_ROW, styled in the brand colour, frozen below it, with
a filter, banded rows that survive sorting (conditional formatting), widths fitted to content and a
number format per column kind. A free-form sheet (several tables, as Borrower 360 tabs have) is written
with `Block`s through `blocks_sheet`.
"""
from __future__ import annotations

import io
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from typing import Any

from openpyxl import Workbook
from openpyxl.formatting.rule import FormulaRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.properties import PageSetupProperties
from openpyxl.worksheet.worksheet import Worksheet

from backend.house_style import (ACCENT, BAND, CENTRED, FONT, FORMATS, HEADER_ROW, INK, MUTED, RULE, STATUS,
                                 STYLE_ID, UNIT_WORDS, WHITE, Meta)

BRAND_FONT = Font(name=FONT, size=9, bold=True, color=ACCENT)
TITLE_FONT = Font(name=FONT, size=15, bold=True, color=INK)
META_FONT = Font(name=FONT, size=9, color=MUTED)
SECTION_FONT = Font(name=FONT, size=11, bold=True, color=ACCENT)
NOTE_FONT = Font(name=FONT, size=9, italic=True, color=MUTED)
BODY_FONT = Font(name=FONT, size=10, color=INK)
LABEL_FONT = Font(name=FONT, size=10, bold=True, color=INK)
HEADER_FONT = Font(name=FONT, size=10, bold=True, color=WHITE)
HEADER_FILL = PatternFill("solid", fgColor=ACCENT)
BAND_FILL = PatternFill("solid", fgColor=BAND, bgColor=BAND)
THIN = Side(style="thin", color=RULE)
HEADER_BORDER = Border(bottom=Side(style="medium", color=ACCENT))
CELL_BORDER = Border(bottom=THIN)
WRAP_TOP = Alignment(vertical="top", wrap_text=True)
MAX_WIDTH = 60
MIN_WIDTH = 8


@dataclass
class Col:
    """A column: the row key it reads, the label it shows, and its kind (a FORMATS key)."""

    key: str
    label: str = ""
    kind: str = ""
    width: float | None = None

    def header(self) -> str:
        label = self.label or self.key.replace("_", " ").capitalize()
        unit = UNIT_WORDS.get(self.kind)
        if unit and unit.lower() not in label.lower() and "sar" not in label.lower():
            label = f"{label} ({unit})"
        return label


def workbook(meta: Meta) -> Workbook:
    """An empty workbook carrying the house-style properties (no default sheet)."""
    wb = Workbook()
    wb.remove(wb.active)
    p = wb.properties
    p.title = meta.title
    p.creator = meta.generated_by or "CreditProbe"
    p.subject = meta.scope_line()
    p.keywords = STYLE_ID
    p.category = "CreditProbe export"
    p.description = meta.generated_line()
    return wb


def header_block(ws: Worksheet, meta: Meta, title: str | None = None) -> None:
    """Rows 1-4: brand line, title, book and period, generated by and when."""
    lines = meta.lines()
    if title:
        lines[1] = title
    fonts = (BRAND_FONT, TITLE_FONT, META_FONT, META_FONT)
    for i, (text, font) in enumerate(zip(lines, fonts), start=1):
        c = ws.cell(row=i, column=1, value=text)
        c.font = font
    ws.row_dimensions[2].height = 22
    ws.sheet_view.showGridLines = False
    ws.sheet_properties.tabColor = ACCENT
    ws.oddFooter.center.text = "CreditProbe · &A · Page &P of &N"
    ws.oddHeader.right.text = meta.classification
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr = PageSetupProperties(fitToPage=True)


def _cell_value(v: Any) -> Any:
    if v is None or isinstance(v, (int, float, str, bool)):
        return v
    if isinstance(v, (list, tuple, set)):
        return ", ".join(str(x) for x in v)
    if hasattr(v, "isoformat"):
        return v
    return str(v)


def _style_header_row(ws: Worksheet, row: int, n: int) -> None:
    for i in range(1, n + 1):
        c = ws.cell(row=row, column=i)
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.border = HEADER_BORDER
        c.alignment = Alignment(vertical="center", wrap_text=True)
    ws.row_dimensions[row].height = 30


def _style_data(ws: Worksheet, first: int, last: int, cols: Sequence[Col]) -> None:
    for j, col in enumerate(cols, start=1):
        fmt = FORMATS.get(col.kind, "General")
        centred = col.kind in CENTRED
        for r in range(first, last + 1):
            c = ws.cell(row=r, column=j)
            c.font = BODY_FONT
            c.border = CELL_BORDER
            if isinstance(c.value, (int, float)) and not isinstance(c.value, bool):
                c.number_format = fmt if fmt != "General" else ("#,##0" if isinstance(c.value, int) else "#,##0.00")
            elif centred:
                c.alignment = Alignment(horizontal="center")
            if isinstance(c.value, str):
                st = STATUS.get(c.value.upper())
                if st:
                    c.fill = PatternFill("solid", fgColor=st[0])
                    c.font = Font(name=FONT, size=10, bold=True, color=st[1])


def band(ws: Worksheet, first_row: int, last_row: int, ncols: int) -> None:
    """Banded rows that stay banded after a sort or filter: conditional formatting, not static fills."""
    if last_row < first_row or ncols < 1:
        return
    ref = f"A{first_row}:{get_column_letter(ncols)}{last_row}"
    ws.conditional_formatting.add(ref, FormulaRule(formula=["MOD(ROW(),2)=0"], fill=BAND_FILL, stopIfTrue=False))


def fit_widths(ws: Worksheet, first_row: int = HEADER_ROW, sample: int = 400, fixed: dict[int, float] | None = None) -> None:
    """Column widths fitted to content (header and the first `sample` rows), between MIN and MAX."""
    widths: dict[int, float] = {}
    for r_i, row in enumerate(ws.iter_rows(min_row=first_row, max_row=first_row + sample)):
        for c in row:
            if c.value is None:
                continue
            v = c.value
            if isinstance(v, float):
                text = f"{v:,.2f}"
            elif isinstance(v, int) and not isinstance(v, bool):
                text = f"{v:,}"
            else:
                text = str(v)
            longest = max((len(x) for x in text.split("\n")), default=0)
            if r_i == 0 and c.row == first_row:
                longest = min(longest, 28) + 2           # headers wrap
            widths[c.column] = max(widths.get(c.column, 0), longest)
    for col, w in widths.items():
        ws.column_dimensions[get_column_letter(col)].width = max(MIN_WIDTH, min(MAX_WIDTH, w + 2))
    for col, w in (fixed or {}).items():
        ws.column_dimensions[get_column_letter(col)].width = w


def table_sheet(wb: Workbook, name: str, meta: Meta, columns: Sequence[Col], rows: Iterable[dict[str, Any] | Sequence[Any]],
                title: str | None = None, note: str | None = None, empty: str = "(no rows)") -> Worksheet:
    """One table on its own sheet, in the house layout. Rows are dicts (read by column key) or sequences."""
    ws = wb.create_sheet(_safe_name(name, wb.sheetnames))
    header_block(ws, meta, title)
    if note:
        ws.cell(row=5, column=1, value=note).font = NOTE_FONT
    for j, col in enumerate(columns, start=1):
        ws.cell(row=HEADER_ROW, column=j, value=col.header())
    _style_header_row(ws, HEADER_ROW, len(columns))
    r = HEADER_ROW
    for row in rows:
        r += 1
        vals = [row.get(c.key) for c in columns] if isinstance(row, dict) else list(row)
        for j, v in enumerate(vals, start=1):
            ws.cell(row=r, column=j, value=_cell_value(v))
    last = r
    if last == HEADER_ROW:
        ws.cell(row=HEADER_ROW + 1, column=1, value=empty).font = NOTE_FONT
    _style_data(ws, HEADER_ROW + 1, last, columns)
    band(ws, HEADER_ROW + 1, max(last, HEADER_ROW + 1), len(columns))
    ws.freeze_panes = ws.cell(row=HEADER_ROW + 1, column=1)
    ws.auto_filter.ref = f"A{HEADER_ROW}:{get_column_letter(max(1, len(columns)))}{max(last, HEADER_ROW + 1)}"
    fit_widths(ws, HEADER_ROW, fixed={j: c.width for j, c in enumerate(columns, start=1) if c.width})
    ws.print_title_rows = f"{HEADER_ROW}:{HEADER_ROW}"
    return ws


def about_sheet(wb: Workbook, meta: Meta, items: Sequence[tuple[str, Any]] = (), index: int | None = None,
                name: str = "About") -> Worksheet:
    """The About sheet: the header block, then Item | Value (meta first, then the export's own items)."""
    seen = {k for k, _ in items}
    rows = [(k, v) for k, v in meta.about_items() if k not in seen] + list(items)
    ws = table_sheet(wb, name, meta, [Col("item", "Item"), Col("value", "Value")], rows, title=f"About · {meta.title}")
    for r in range(HEADER_ROW + 1, ws.max_row + 1):
        ws.cell(row=r, column=1).font = LABEL_FONT
        ws.cell(row=r, column=2).alignment = WRAP_TOP
    ws.column_dimensions["A"].width = max(ws.column_dimensions["A"].width or 0, 26)
    ws.column_dimensions["B"].width = 90
    if index is not None:
        wb.move_sheet(ws, offset=index - wb.sheetnames.index(ws.title))
    return ws


# ------------------------------------------------------------------ free-form sheets (several tables)
@dataclass
class Block:
    """One part of a free-form sheet: a section title, a note, key-value pairs, or a table."""

    title: str = ""
    note: str = ""
    pairs: Sequence[tuple[str, Any, str]] = ()      # (label, value, kind)
    columns: Sequence[Col] = ()
    rows: Sequence[dict[str, Any] | Sequence[Any]] = ()
    row_kinds: Sequence[Sequence[str]] | None = None  # per-row kinds where a column's unit varies by row
    empty: str = "(no rows)"


def blocks_sheet(wb: Workbook, name: str, meta: Meta, blocks: Sequence[Block], title: str | None = None) -> Worksheet:
    """A sheet of several blocks under one header block. The first table block gets the frozen header and filter."""
    ws = wb.create_sheet(_safe_name(name, wb.sheetnames))
    header_block(ws, meta, title)
    r = HEADER_ROW - 1
    first_table: tuple[int, int, int] | None = None
    for b in blocks:
        if b.title:
            r += 1
            ws.cell(row=r, column=1, value=b.title).font = SECTION_FONT
        if b.note:
            r += 1
            ws.cell(row=r, column=1, value=b.note).font = NOTE_FONT
        for label, value, kind in b.pairs:
            r += 1
            ws.cell(row=r, column=1, value=label).font = LABEL_FONT
            c = ws.cell(row=r, column=2, value=_cell_value(value))
            c.font = BODY_FONT
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                c.number_format = FORMATS.get(kind) or ("#,##0" if isinstance(value, int) else "#,##0.00")
        if b.columns:
            r += 1
            head = r
            for j, col in enumerate(b.columns, start=1):
                ws.cell(row=r, column=j, value=col.header())
            _style_header_row(ws, r, len(b.columns))
            for i, row in enumerate(b.rows):
                r += 1
                vals = [row.get(c.key) for c in b.columns] if isinstance(row, dict) else list(row)
                for j, v in enumerate(vals, start=1):
                    ws.cell(row=r, column=j, value=_cell_value(v))
            if not b.rows:
                r += 1
                ws.cell(row=r, column=1, value=b.empty).font = NOTE_FONT
                band(ws, r, r, len(b.columns))
            else:
                _style_data(ws, head + 1, r, b.columns)
                if b.row_kinds:
                    for i, kinds in enumerate(b.row_kinds):
                        for j, kind in enumerate(kinds, start=1):
                            c = ws.cell(row=head + 1 + i, column=j)
                            if kind and isinstance(c.value, (int, float)) and not isinstance(c.value, bool):
                                c.number_format = FORMATS.get(kind, c.number_format)
                band(ws, head + 1, r, len(b.columns))
            if first_table is None:
                first_table = (head, r, len(b.columns))
        r += 1                                         # a blank row between blocks
    if first_table:
        head, last, n = first_table
        ws.freeze_panes = ws.cell(row=head + 1, column=1)
        ws.auto_filter.ref = f"A{head}:{get_column_letter(n)}{max(last, head + 1)}"
    else:
        ws.freeze_panes = ws.cell(row=HEADER_ROW, column=1)
    fit_widths(ws, HEADER_ROW)
    if (ws.column_dimensions["A"].width or 0) < 24:
        ws.column_dimensions["A"].width = 24
    return ws


def _safe_name(name: str, used: Sequence[str]) -> str:
    import re
    base = re.sub(r"[\[\]:*?/\\]", "-", name).strip()[:31] or "Sheet"
    out, i = base, 2
    while out in used:
        out = f"{base[:28]}-{i}"
        i += 1
    return out


def to_bytes(wb: Workbook) -> bytes:
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def read_table(ws: Worksheet) -> tuple[list[Any], list[tuple[Any, ...]]]:
    """(header, rows) of a house-style table sheet: the header is on HEADER_ROW."""
    rows = list(ws.iter_rows(min_row=HEADER_ROW, values_only=True))
    if not rows:
        return [], []
    header = list(rows[0])
    data = [r for r in rows[1:] if any(v is not None for v in r)]
    if len(data) == 1 and isinstance(data[0][0], str) and data[0][0].startswith("(") and all(v is None for v in data[0][1:]):
        data = []
    return header, data


def read_about(wb: Any, name: str = "About") -> dict[str, Any]:
    _, rows = read_table(wb[name])
    return {r[0]: r[1] if len(r) > 1 else None for r in rows}


