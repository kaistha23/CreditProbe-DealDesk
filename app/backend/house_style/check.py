"""Does a file carry the house style? Used by tests/v5/house_style and by the UAT sweep on every download.

    problems = check.xlsx(path_or_bytes)     # [] when the workbook is in house style
    problems = check.docx(path_or_bytes)

Both also apply the label rule (no "Synthetic" or "Demo" anywhere in the file's text).
"""
from __future__ import annotations

import io
import re
from pathlib import Path
from typing import Any

from backend.house_style import ACCENT, HEADER_ROW, STYLE_ID

BANNED = re.compile(r"synthetic|(?<![\w-])demo(?![\w-])|demo[- ]data", re.I)


def _open(src: Any) -> io.BytesIO | str:
    if isinstance(src, (bytes, bytearray)):
        return io.BytesIO(src)
    return str(src) if isinstance(src, Path) else src


def _rgb(colour: Any) -> str:
    v = getattr(colour, "rgb", None) or ""
    return str(v)[-6:].upper() if isinstance(v, str) else ""


def _sample(src: Any, keep_rows: int = 300) -> io.BytesIO:
    """The same workbook with each large sheet cut to its first rows (styles, panes, filter, banding kept)."""
    import zipfile
    raw = Path(src).read_bytes() if isinstance(src, (str, Path)) else bytes(src)
    zin = zipfile.ZipFile(io.BytesIO(raw))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=1) as zout:
        for info in zin.infolist():
            data = zin.read(info.filename)
            if info.filename.startswith("xl/worksheets/") and len(data) > 1_000_000:
                start = data.find(b"<sheetData>")
                end = data.rfind(b"</sheetData>")
                pos = start
                for _ in range(keep_rows):
                    nxt = data.find(b"</row>", pos + 1, end)
                    if nxt < 0:
                        break
                    pos = nxt
                if start >= 0 and end > pos > start:
                    data = data[:pos + len(b"</row>")] + data[end:]
            zout.writestr(info, data)
    out.seek(0)
    return out


def xlsx(src: Any) -> list[str]:
    import openpyxl
    wb = openpyxl.load_workbook(_sample(src))
    out: list[str] = []
    if (wb.properties.keywords or "") != STYLE_ID:
        out.append(f"workbook properties lack the house-style marker ({wb.properties.keywords!r})")
    if "About" not in wb.sheetnames:
        out.append("no About sheet")
    for ws in wb.worksheets:
        name = ws.title
        a1, a2, a4 = ws["A1"].value, ws["A2"].value, ws["A4"].value
        if a1 != "CREDITPROBE":
            out.append(f"{name}: no header block (A1 {a1!r})")
            continue
        if not a2 or not ws["A2"].font.b or (ws["A2"].font.sz or 0) < 14:
            out.append(f"{name}: the title (A2) is not in the title style")
        if not (isinstance(a4, str) and a4.startswith("Generated by ") and " on " in a4):
            out.append(f"{name}: no 'Generated by … on …' line (A4 {a4!r})")
        if not ws.freeze_panes:
            out.append(f"{name}: no frozen panes")
        if not ws.auto_filter.ref:
            out.append(f"{name}: no filter")
        head_row = int(re.sub(r"[A-Z]+", "", ws.auto_filter.ref.split(":")[0])) if ws.auto_filter.ref else HEADER_ROW
        hc = ws.cell(row=head_row, column=1)
        if _rgb(hc.fill.fgColor) != ACCENT or not hc.font.b:
            out.append(f"{name}: header row {head_row} is not in the brand style")
        rules = [r for rng in ws.conditional_formatting for r in rng.rules]
        if not any("MOD(ROW()" in "".join(r.formula or []) for r in rules):
            out.append(f"{name}: no banded rows")
        widths = [d.width for k, d in ws.column_dimensions.items() if d.width]
        if not widths:
            out.append(f"{name}: column widths not fitted")
        unformatted = 0
        for row in ws.iter_rows(min_row=head_row + 1, max_row=min(ws.max_row, head_row + 200)):
            for c in row:
                if isinstance(c.value, float) and c.number_format == "General":
                    unformatted += 1
        if unformatted:
            out.append(f"{name}: {unformatted} decimal cells without a number format")
        text = " ".join(str(c) for row in ws.iter_rows(values_only=True) for c in row if isinstance(c, str))
        m = BANNED.search(text)
        if m:
            out.append(f"{name}: banned label {m.group(0)!r}")
    return out


def docx(src: Any, cover: bool = True) -> list[str]:
    from docx import Document
    doc = Document(_open(src))
    out: list[str] = []
    xml = doc.element.xml
    if (doc.core_properties.keywords or "") != STYLE_ID:
        out.append(f"document properties lack the house-style marker ({doc.core_properties.keywords!r})")
    sec = doc.sections[0]
    footer = sec.footer._element.xml
    if "PAGE" not in footer or "NUMPAGES" not in footer:
        out.append("footer has no 'Page X of Y'")
    if "CREDITPROBE" not in sec.header._element.xml:
        out.append("no running header")
    if cover:
        if not sec.different_first_page_header_footer:
            out.append("no cover page (first page header not separate)")
        if not any(p.style.name == "CP Cover Title" for p in doc.paragraphs[:12]):
            out.append("no cover title")
        if 'w:type="page"' not in xml:
            out.append("cover is not followed by a page break")
    h1 = doc.styles["Heading 1"]
    if str(h1.font.color.rgb or "").upper() != ACCENT:
        out.append("Heading 1 is not in the brand colour")
    if not any(p.style.name.startswith("Heading") for p in doc.paragraphs):
        out.append("no headings")
    for i, t in enumerate(doc.tables):
        if t.style is not None and t.style.name == "CP Table":
            fill = t.rows[0].cells[0]._tc.xml
            if ACCENT not in fill.upper():
                out.append(f"table {i + 1}: header row not in the brand colour")
    if not any(t.style is not None and t.style.name == "CP Table" for t in doc.tables):
        out.append("no table in the house table style")
    text = "\n".join(p.text for p in doc.paragraphs) + "\n" + "\n".join(
        c.text for t in doc.tables for r in t.rows for c in r.cells)
    m = BANNED.search(text)
    if m:
        out.append(f"banned label {m.group(0)!r}")
    return out


def any_file(path: str | Path) -> list[str]:
    p = str(path)
    if p.endswith(".xlsx"):
        return xlsx(path)
    if p.endswith(".docx"):
        return docx(path)
    return []


__all__ = ["xlsx", "docx", "any_file"]
