"""The branch / relationship-manager reference domain (PLAN_R4 B4).

The books carry a region but no branch, business unit or relationship manager. This domain adds them, keyed to the
v5 spine: every corporate borrower (CB#####) at every quarter the book holds it, and every retail customer
(RC######) at every month the book holds it, gets exactly one branch, and that branch is in the customer's own
book region. Corporate borrowers are booked at a branch with a corporate desk, sit in a business unit (Large
Corporates for the book's Strategic tier, otherwise the regional Corporate Banking unit) and have one relationship
manager of that unit. A customer keeps its branch and RM across periods.

  branch_reference            branch_id, branch_name, city, region, area, corporate_desk
  branch_rm_reference         rm_id, rm_name, business_unit, base_branch_id, region
  branch_corporate_quarter    borrower x quarter: region, branch, business unit, RM
  branch_retail_month         customer x month: region, branch

Deterministic: one fixed seed, inputs read and walked in sorted order, outputs written sorted, so a rebuild writes
the same rows. tests/v5/test_sync_branches.py checks the keys, the periods, the regions and the rebuild.
Provenance (manifest only, never on screen): generated, describes no real branch staffing or person.
"""
