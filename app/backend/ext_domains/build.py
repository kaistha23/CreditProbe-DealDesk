"""Synthetic Bureau (SIMAH-style) and Open Banking domains, keyed to the v5 spine.

Two new data domains, each its own release under data/external/:

  bureau-saudi-v1        bureau_retail_month       customer_id x reporting_month
                         bureau_corp_quarter       borrower_id x reporting_quarter
  open-banking-saudi-v1  openbanking_retail_month  customer_id x reporting_month
                         openbanking_corp_quarter  borrower_id x reporting_quarter

Every row is one owner and period of the book's own customer table (the same
IDs and the same periods, nothing more and nothing less; tests/v5/
test_sync_external.py checks it). The books are opened read-only.

COHERENT WITH THE BOOKS. Each owner's external state is driven by a latent
stress index built from its INTERNAL risk at that period (behaviour score,
DPD and stage for retail; PD, DPD, stage and watchlist for corporate), plus a
persistent owner effect and AR(1) noise, so weak internal names tend to look
weak externally but not always. A share of owners that are still
performing internally at the as-of date (set per story group, STORY below) carry an EXTERNAL-FIRST shock that
builds over the last few periods: their bureau and bank-account signals turn
before the bank's own book does. That is the early-warning value the new rules
look for.

Deterministic: a fixed seed per domain and book, inputs read in a fixed order,
outputs written ORDERED, so a rebuild writes the same bytes.

SYNTHETIC DATA. Describes no real person, company or bureau record.
"""
