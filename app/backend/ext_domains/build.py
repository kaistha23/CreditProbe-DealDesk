def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def _ar1(owner_codes: np.ndarray, n_periods: int, rng: np.random.Generator,
         rho: float, sd: float) -> np.ndarray:
    """AR(1) noise per owner over the period index (rows sorted owner, period)."""
    n_owners = owner_codes.max() + 1
    shocks = rng.normal(0, sd, size=(n_owners, n_periods))
    out = np.zeros_like(shocks)
    out[:, 0] = shocks[:, 0] / np.sqrt(1 - rho ** 2)
    for t in range(1, n_periods):
        out[:, t] = rho * out[:, t - 1] + shocks[:, t]
    return out


#: THE EARLY WARNING STORY (PLAN_R5 Session E, gw-ews-1.3.0; docs/v5/EWS_STORY.md section 3).
#: Up to gw-ews-1.2.0 one external-first shock was drawn at random across the whole book, so the
#: external signals worsened in every segment together. Now each owner belongs to a story GROUP
#: (fixed per owner, from its latest row), and each group has:
#:   first_share  the share of its still-performing owners whose external signals turn first;
#:   path         a shift of the latent stress by periods before the as-of date (0 = as-of).
#: Deteriorating groups drift up, improving groups drift down at the end, stable groups do not move.
STORY = {
    "corporate": {
        "building_contracting": {"first_share": 0.15, "path": {2: 0.3, 1: 0.7, 0: 1.2}},
        "construction": {"first_share": 0.06, "path": {1: 0.3, 0: 0.6}},
        "civil_infrastructure": {"first_share": 0.0, "path": {2: 0.3, 1: 0.9, 0: -1.2}},
        "real_estate": {"first_share": 0.06, "path": {2: 0.2, 1: 0.4, 0: 0.8}},
        "makkah_hospitality": {"first_share": 0.10, "path": {0: 1.0}},
        "hospitality": {"first_share": 0.03, "path": {0: 0.2}},
        "improving": {"first_share": 0.0, "path": {1: 0.6, 0: -0.8}},
        "stable": {"first_share": 0.02, "path": {}},
    },
    "retail": {
        "card_recent_vintage": {"first_share": 0.12, "path": {2: 0.3, 1: 0.6, 0: 1.0}},
        "bnpl": {"first_share": 0.05, "path": {1: 0.2, 0: 0.4}},
        "personal_finance_qassim": {"first_share": 0.10, "path": {2: 0.3, 1: 0.6, 0: 0.9}},
        "secured": {"first_share": 0.0, "path": {2: 0.2, 1: 0.2, 0: -1.2}},
        "stable": {"first_share": 0.01, "path": {0: -0.25}},
    },
}
#: Regions whose not-deteriorating owners also improve at the end (shift by periods before as-of).
STORY_REGIONS = {
    "corporate": {r: {1: 0.3, 0: -1.2} for r in ("Asir", "Tabuk", "Hail", "Northern Borders")},
    "retail": {"Riyadh": {1: 0.2, 0: -0.5}, "Eastern Province": {1: 0.2, 0: -0.5}},
}
#: Story groups that the regional improvement does not reach.
DETERIORATING_GROUPS = ("building_contracting", "construction", "real_estate", "makkah_hospitality",
                        "card_recent_vintage", "bnpl", "personal_finance_qassim")
IMPROVING_SECTORS = ("Healthcare", "Power and Utilities", "Telecommunications")
STORY_REGION_RETAIL = "Qassim"
#: A card booked in the last 12 months is a recent vintage (the "younger cohort").
RECENT_VINTAGE_MONTHS = 12


def corporate_group(sector: str, sub_sector: str, region: str) -> str:
    if sector == "Construction":
        return {"Building Contracting": "building_contracting",
                "Civil Infrastructure": "civil_infrastructure"}.get(sub_sector, "construction")
    if sector == "Real Estate":
        return "stable" if region == "Makkah" else "real_estate"
    if sector == "Hospitality":
        return "makkah_hospitality" if region == "Makkah" else "hospitality"
    return "improving" if sector in IMPROVING_SECTORS else "stable"


def retail_groups(src: pathlib.Path) -> pd.Series:
    """customer_id -> story group, from the customer's accounts in its latest month."""
    a = pd.read_parquet(src / "retail_account_month.parquet",
                        columns=["customer_id", "reporting_month", "product", "origination_month", "region"])
    last = a.groupby("customer_id").reporting_month.transform("max")
    a = a[a.reporting_month == last]
    as_of = pd.Period(a.reporting_month.max(), "M")
    cutoff = str(as_of - (RECENT_VINTAGE_MONTHS - 1))
    g = a.assign(card_recent=(a["product"] == "Credit Card") & (a.origination_month >= cutoff),
                 bnpl=a["product"] == "Buy Now Pay Later",
                 pf_region=(a["product"] == "Personal Finance") & (a.region == STORY_REGION_RETAIL),
                 secured=a["product"].isin(["Mortgage", "Auto Finance"])).groupby("customer_id").agg(
        card_recent=("card_recent", "any"), bnpl=("bnpl", "any"), pf_region=("pf_region", "any"),
        secured=("secured", "all"))
    return pd.Series(np.select([g.card_recent, g.bnpl, g.pf_region, g.secured],
                               ["card_recent_vintage", "bnpl", "personal_finance_qassim", "secured"], "stable"),
                     index=g.index).sort_index()


def _latent(frame: pd.DataFrame, owner: str, period: str, internal: np.ndarray,
            bad_now: pd.Series, domain_id: str, rng: np.random.Generator,
            group: pd.Series, region: pd.Series | None = None) -> tuple[np.ndarray, np.ndarray]:
    """Latent external stress z per row, and the external-first flag per row.

    `group` maps each owner to its story group (STORY[domain_id])."""
    periods = sorted(frame[period].unique())
    pidx = frame[period].map({p: i for i, p in enumerate(periods)}).to_numpy()
    codes, uniques = pd.factorize(frame[owner], sort=True)
    effect = rng.normal(0, 0.55, size=len(uniques))
    noise = _ar1(codes, len(periods), rng, rho=0.7, sd=0.35)[codes, pidx]
    story = STORY[domain_id]
    # External-first: owners performing at the as-of date, drawn per story group.
    performing = sorted(set(uniques) - set(bad_now[bad_now].index))
    chosen: set = set()
    for name in sorted(story):
        pool = [o for o in performing if group.get(o, "stable") == name]
        k = int(round(story[name]["first_share"] * len(pool)))
        if k:
            chosen |= set(rng.choice(np.array(pool, dtype=object), size=k, replace=False))
    start = {o: len(periods) - int(rng.integers(2, 5)) for o in sorted(chosen)}
    first = frame[owner].isin(chosen).to_numpy()
    begin = frame[owner].map(start).fillna(len(periods) + 1).to_numpy()
    shock = np.where(first, np.clip(pidx - begin + 1, 0, None) * 0.9, 0.0)
    # The group's path, by periods before the as-of date.
    back = len(periods) - 1 - pidx
    row_group = frame[owner].map(group).fillna("stable").to_numpy()
    drift = np.zeros(len(frame))
    for name, spec in story.items():
        in_group = row_group == name
        for offset, shift in spec["path"].items():
            drift[in_group & (back == offset)] += shift
    # Internal risk RELATIVE TO THE PERIOD (gw-ews-1.3.0): standardised within each period, so the
    # books' portfolio-wide drift (EWS_STORY.md section 1) is not copied into every owner's external
    # signals; the owner's rank in its own book still drives them, and the story paths add the trend.
    s = pd.Series(internal)
    by = s.groupby(pidx)
    if region is not None:
        row_region = frame[owner].map(region).fillna("").to_numpy()
        for name, path in STORY_REGIONS[domain_id].items():
            reach = (row_region == name) & ~np.isin(row_group, DETERIORATING_GROUPS)
            for offset, shift in path.items():
                drift[reach & (back == offset)] += shift
    internal_std = ((s - by.transform("mean")) / by.transform("std").replace(0, 1.0)).to_numpy()
    z = 0.75 * internal_std + effect[codes] + noise + shock + drift
    return z, first & (pidx >= begin)


def _trend(frame: pd.DataFrame, owner: str, period: str, value: np.ndarray, lag: int) -> np.ndarray:
    """Percent change against `lag` periods earlier for the same owner (0 where unknown)."""
    s = pd.Series(value, index=frame.index)
    prev = s.groupby(frame[owner]).shift(lag)
    pct = 100.0 * (s - prev) / prev.abs().where(prev.abs() > 1e-9)
    return pct.fillna(0.0).clip(-95, 300).round(1).to_numpy()


def retail(rng_b: np.random.Generator, rng_o: np.random.Generator) -> tuple[pd.DataFrame, pd.DataFrame]:
    src = SOURCE_LAKE / RET_SRC
    c = pd.read_parquet(src / "retail_customer_month.parquet",
                        columns=["tenant_id", "customer_id", "reporting_month", "employment_type",
                                 "behaviour_score", "worst_dpd_days", "worst_stage", "total_ead_sar_mn", "region"])
    c = c.sort_values(["customer_id", "reporting_month"]).reset_index(drop=True)
    acc = pd.read_parquet(src / "retail_account_month.parquet",
                          columns=["customer_id", "reporting_month", "default_flag"])
    dflt = acc.groupby(["customer_id", "reporting_month"]).default_flag.max()
    c["default_flag"] = c.set_index(["customer_id", "reporting_month"]).index.map(dflt).fillna(0).astype(int)
    dpd = c.worst_dpd_days.fillna(0).to_numpy()
    stage = c.worst_stage.fillna(1).to_numpy()
    internal = ((700 - c.behaviour_score.fillna(650).to_numpy()) / 80 + 1.0 * (dpd > 0) + 1.5 * (dpd >= 30)
                + 2.0 * (stage == 3) + 0.7 * (stage == 2))
    as_of = c.reporting_month.max()
    now = c[c.reporting_month == as_of].set_index("customer_id")
    bad_now = (now.worst_dpd_days >= 90) | (now.worst_stage == 3) | (now.default_flag == 1)

    group = retail_groups(src)
    region = c.groupby("customer_id").region.last().sort_index()

    # ---- Bureau
    z, first = _latent(c, "customer_id", "reporting_month", internal, bad_now, "retail", rng_b, group, region)
    n = len(c)
    score = np.clip(np.round(715 - 58 * z + rng_b.normal(0, 18, n)), 300, 900).astype(int)
    p_dpd = _sigmoid(1.35 * z - 3.3)
    has_dpd = rng_b.random(n) < p_dpd
    sev = np.clip(z + rng_b.normal(0, 0.8, n), -5, 5)
    ext_dpd = np.where(has_dpd, np.select([sev < 0.8, sev < 1.8, sev < 2.6], [12, 35, 65], 95), 0)
    status = np.select([ext_dpd == 0, ext_dpd < 30, ext_dpd < 60, ext_dpd < 90],
                       ["Current", "1-29 DPD", "30-59 DPD", "60-89 DPD"], "90+ DPD")
    prev_dpd = pd.Series(ext_dpd).groupby(c.customer_id).shift(1).fillna(0).to_numpy()
    facilities = rng_b.poisson(1.4 + 0.45 * np.clip(z, 0, None)).astype(int)
    balance = np.round(c.total_ead_sar_mn.fillna(0).to_numpy() * np.exp(rng_b.normal(-0.2, 0.5, n))
                       * (0.6 + 0.25 * facilities), 5)
    leverage = np.round(np.clip(0.28 + 0.11 * z + rng_b.normal(0, 0.06, n), 0.02, 2.5), 3)
    enq = rng_b.poisson(0.7 + 0.95 * np.clip(z, 0, None)).astype(int)
    bureau = pd.DataFrame({
        "tenant_id": c.tenant_id, "customer_id": c.customer_id, "reporting_month": c.reporting_month,
        "bureau_score": score, "external_dpd_days": ext_dpd.astype(int), "worst_external_status": status,
        "external_facilities": facilities, "external_balance_sar_mn": balance,
        "external_leverage_x": leverage, "enquiries_3m": enq,
        "new_external_default": ((ext_dpd >= 90) & (prev_dpd < 90)).astype(int),
        "external_first_flag": first.astype(int)})

    # ---- Open Banking (its own latent: correlated with internal risk, independent noise)
    z, first = _latent(c, "customer_id", "reporting_month", internal, bad_now, "retail", rng_o, group, region)
    salaried = c.employment_type.fillna("").str.startswith("Salaried").to_numpy()
    interrupt = salaried & (rng_o.random(n) < _sigmoid(1.25 * z - 3.9))
    # Income is the customer's own (persistent); a month adds only small noise.
    codes, uniques = pd.factorize(c.customer_id, sort=True)
    income = np.exp(rng_o.normal(0, 0.35, len(uniques)))[codes]
    base = np.where(salaried, 19.0, 14.0) * income * np.exp(rng_o.normal(0, 0.06, n))  # SAR thousand a month
    inflows = np.round(base * np.exp(-0.16 * z) * np.where(interrupt, 0.35, 1.0), 3)
    trend = _trend(c, "customer_id", "reporting_month", inflows, 3)
    buffer = np.round(np.clip(np.exp(1.0 - 0.5 * z + rng_o.normal(0, 0.35, n)), 0, 24), 2)
    returned = rng_o.poisson(0.15 + 0.55 * np.clip(z, 0, None)).astype(int)
    share = np.round(np.clip(2.0 + 3.2 * np.clip(z, 0, None) + rng_o.normal(0, 1.8, n), 0, 60), 1)
    ob = pd.DataFrame({
        "tenant_id": c.tenant_id, "customer_id": c.customer_id, "reporting_month": c.reporting_month,
        "salaried_flag": salaried.astype(int),
        "salary_credit_flag": np.where(salaried, (~interrupt).astype(int), 0),
        "salary_interruption_flag": interrupt.astype(int),
        "total_inflows_sar_k": inflows, "inflow_trend_pct": trend,
        "balance_buffer_months": buffer, "returned_payments_3m": returned,
        "gambling_bnpl_spend_share_pct": share, "external_first_flag": first.astype(int)})
    return bureau, ob


def corporate(rng_b: np.random.Generator, rng_o: np.random.Generator) -> tuple[pd.DataFrame, pd.DataFrame]:
    src = SOURCE_LAKE / CORP_SRC
    b = pd.read_parquet(src / "corp_borrower_quarter.parquet",
                        columns=["tenant_id", "borrower_id", "reporting_quarter", "pd_ttc_12m", "watchlist_flag",
                                 "revenue_sar_mn", "sector", "sub_sector", "region"])
    b = b.sort_values(["borrower_id", "reporting_quarter"]).reset_index(drop=True)
    f = pd.read_parquet(src / "corp_facility_quarter.parquet",
                        columns=["borrower_id", "reporting_quarter", "dpd_days", "stage", "default_flag", "ead_sar_mn"])
    agg = f.groupby(["borrower_id", "reporting_quarter"]).agg(
        dpd=("dpd_days", "max"), stage=("stage", "max"), dflt=("default_flag", "max"), ead=("ead_sar_mn", "sum"))
    b = b.join(agg, on=["borrower_id", "reporting_quarter"])
    dpd = b.dpd.fillna(0).to_numpy()
    stage = b.stage.fillna(1).to_numpy()
    pd_ = b.pd_ttc_12m.fillna(0.01).clip(lower=1e-4).to_numpy()
    internal = (np.log(pd_ / 0.006) + 1.0 * (dpd > 0) + 2.0 * (stage == 3) + 0.7 * (stage == 2)
                + 0.5 * b.watchlist_flag.fillna(0).to_numpy())
    as_of = b.reporting_quarter.max()
    now = b[b.reporting_quarter == as_of].set_index("borrower_id")
    bad_now = (now.dpd.fillna(0) >= 90) | (now.stage == 3) | (now.dflt == 1)
    n = len(b)
    group = pd.Series([corporate_group(*x) for x in zip(now.sector, now.sub_sector, now.region)],
                      index=now.index).sort_index()
    region = now.region.sort_index()

    z, first = _latent(b, "borrower_id", "reporting_quarter", internal, bad_now, "corporate", rng_b, group, region)
    has_dpd = rng_b.random(n) < _sigmoid(1.3 * z - 3.4)
    sev = np.clip(z + rng_b.normal(0, 0.8, n), -5, 5)
    ext_dpd = np.where(has_dpd, np.select([sev < 0.8, sev < 1.8, sev < 2.6], [15, 45, 75], 120), 0)
    bureau = pd.DataFrame({
        "tenant_id": b.tenant_id, "borrower_id": b.borrower_id, "reporting_quarter": b.reporting_quarter,
        "external_exposure_sar_mn": np.round(b.ead.fillna(0).to_numpy() * 0.55 * np.exp(rng_b.normal(0, 0.45, n)), 5),
        "external_dpd_days": ext_dpd.astype(int),
        "external_default_flag": (ext_dpd >= 90).astype(int),
        "enquiries_q": rng_b.poisson(0.45 + 0.65 * np.clip(z, 0, None)).astype(int),
        "external_first_flag": first.astype(int)})

    z, first = _latent(b, "borrower_id", "reporting_quarter", internal, bad_now, "corporate", rng_o, group, region)
    inflows = np.round(b.revenue_sar_mn.fillna(0).clip(lower=0).to_numpy() / 4 * 0.92
                       * np.exp(-0.14 * z + rng_o.normal(0, 0.08, n)), 4)
    ob = pd.DataFrame({
        "tenant_id": b.tenant_id, "borrower_id": b.borrower_id, "reporting_quarter": b.reporting_quarter,
        "operating_inflows_sar_mn": inflows,
        # Year on year (gw-ews-1.3.0): quarterly revenue is seasonal, so a change on the previous
        # quarter fired every Q1 (EWS_STORY.md section 1.2).
        "inflow_trend_pct": _trend(b, "borrower_id", "reporting_quarter", inflows, 4),
        "balance_buffer_months": np.round(np.clip(np.exp(1.15 - 0.45 * z + rng_o.normal(0, 0.3, n)), 0, 24), 2),
        "returned_payments_q": rng_o.poisson(0.1 + 0.45 * np.clip(z, 0, None)).astype(int),
        "external_first_flag": first.astype(int)})
    return bureau, ob


def _write(frame: pd.DataFrame, path: pathlib.Path) -> dict:
    path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(path, index=False, compression="zstd")
    return {"rows": int(len(frame)), "columns": list(frame.columns),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


