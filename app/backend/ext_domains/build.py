def main() -> None:
    out: dict[str, dict] = {}
    seed = SEED
    r_bur, r_ob = retail(np.random.default_rng(seed), np.random.default_rng(seed + 1))
    c_bur, c_ob = corporate(np.random.default_rng(seed + 2), np.random.default_rng(seed + 3))
    for release, files, label in (
            (BUREAU, {"bureau_retail_month": r_bur, "bureau_corp_quarter": c_bur}, "Bureau (SIMAH-style)"),
            (OPEN_BANKING, {"openbanking_retail_month": r_ob, "openbanking_corp_quarter": c_ob}, "Open Banking")):
        rel = {}
        for name, frame in files.items():
            rel[name] = _write(frame, EXTERNAL / release / f"{name}.parquet")
        manifest = {
            "release_id": release, "domain_label": label, "origin": "SYNTHETIC_DEMO", "not_client_data": SYNTHETIC,
            "label": "Synthetic data", "builder": "backend/ext_domains/build.py", "seed": seed,
            "keyed_to": {"retail": {"release": RET_SRC, "keys": ["customer_id", "reporting_month"]},
                         "corporate": {"release": CORP_SRC, "keys": ["borrower_id", "reporting_quarter"]}},
            "story": STORY,
            "relations": rel,
            "dictionary": {k: dict(zip(("type", "unit", "description"), v)) for k, v in DICTIONARY.items()
                           if any(k in r["columns"] for r in rel.values())},
        }
        (EXTERNAL / release / "manifest.json").write_text(json.dumps(manifest, indent=1))
        out[release] = {k: v["rows"] for k, v in rel.items()}
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
