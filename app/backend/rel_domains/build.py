"""The relationship domain: group, supplier, customer, guarantor, shared-collateral and shared-person links.

A data domain of its own (data/relationships/rel-saudi-v1), keyed to the v5 spine: every borrower is a book
borrower (CB#####), every customer a book customer (RC######), every facility one the book holds (CF######), every
quarter or month one the book carries, and the group field is reconciled to the book's own `group_id` (CG####).
tests/v5/test_sync_relationships.py checks all of it, and that a rebuild writes the same bytes.

  rel_group_quarter       borrower x quarter for every borrower in a connected group: group, role, ownership
  rel_edge_quarter        edge x quarter: GROUP (ownership), SUPPLIES, GUARANTEES, SHARES_COLLATERAL
  rel_person_role         owner / chairman / director / CEO persons and the companies they hold a role in
  rel_shared_collateral   one pledged asset shared by two or more borrowers, per quarter, with each claim
  rel_household_month     retail customers living in one household (customer x month)
  rel_employer_month      retail customers and the corporate borrower that employs them (customer x month)

WHAT IT FIXES. The book's group field holds seven artefact mega-groups of 242 to 620 borrowers each, every one of
a single sector. Here each of them is carved into groups of three to nine related companies of the same sub-sector
and region, so a group is a handful of companies. The book is not touched: `legacy_group_id` keeps the book's own
value, and a new group id is always `<legacy id>-<nnn>`, so every group sits inside exactly one book group.

COHERENT WITH THE BOOKS. A supplier edge sells at most 60% of the supplier's revenue and the buyer's in-book
suppliers supply at most 80% of its purchases (the rest comes from names outside the bank's book); a guarantee
exists only for a facility whose collateral row is a Corporate Guarantee, at that row's allocated value; a shared
asset's claims point at the borrowers' own collateral rows; an employer is a corporate borrower in the retail
customer's region.

Deterministic: fixed seeds, inputs read in a fixed order, outputs written ordered, so a rebuild writes the same
bytes. SYNTHETIC: it describes no real company, family, group, person or relationship.
"""
