def _sha(frame: pd.DataFrame) -> str:
    return hashlib.sha256(pd.util.hash_pandas_object(frame, index=False).values.tobytes()).hexdigest()


def _chunks(n: int, rng: np.random.Generator) -> list[int]:
    """Sizes of three to nine that add up to n (n >= 3)."""
    sizes: list[int] = []
    left = n
    while left > 0:
        k = int(rng.choice([3, 4, 5, 6, 7, 8, 9], p=[.20, .28, .22, .14, .08, .05, .03]))
        if left - k in (1, 2):
            k = left  # never leave one or two over
        k = min(k, left)
        sizes.append(k)
        left -= k
    if len(sizes) > 1 and sizes[-1] < 3:
        sizes[-2] += sizes.pop()
    return sizes


def corporate(rng_root: int) -> dict[str, pd.DataFrame]:
    src = SOURCE_LAKE / CORP_SRC
    b = pd.read_parquet(src / "corp_borrower_quarter.parquet",
                        columns=["tenant_id", "borrower_id", "borrower_name", "reporting_quarter", "group_id", "group_name",
                                 "sector", "sub_sector", "region", "revenue_sar_mn", "ebitda_sar_mn"])
    f = pd.read_parquet(src / "corp_facility_quarter.parquet",
                        columns=["facility_id", "borrower_id", "reporting_quarter", "ead_sar_mn"])
    col = pd.read_parquet(src / "corp_collateral_quarter.parquet",
                          columns=["collateral_id", "facility_id", "borrower_id", "reporting_quarter", "collateral_type",
                                   "market_value_sar_mn", "allocated_value_sar_mn"])
    quarters = sorted(b.reporting_quarter.unique())
    last = quarters[-1]
    tenant = b.tenant_id.iloc[0]
    ead = f.groupby(["borrower_id", "reporting_quarter"]).ead_sar_mn.sum().rename("ead").reset_index()
    st = b[b.reporting_quarter == last].merge(ead[ead.reporting_quarter == last][["borrower_id", "ead"]],
                                              on="borrower_id", how="left").fillna({"ead": 0.0})
    st = st.sort_values("borrower_id").reset_index(drop=True)
    names = dict(zip(st.borrower_id, st.borrower_name))
    qi = {q: i for i, q in enumerate(quarters)}

    # ---------------------------------------------------------------- groups
    rng = np.random.default_rng(rng_root + 1)
    members: list[dict] = []
    used_names: set[str] = set(st.group_name.unique()) | set(st.borrower_name.unique())

    def new_group(gid: str, legacy: str, legacy_name: str, ids: list[str], name: str | None) -> None:
        sub = st.set_index("borrower_id").loc[ids]
        order = sub.sort_values(["ead", "borrower_name"], ascending=[False, True]).index.tolist()
        parent = order[0]
        gname = name or f"{names[parent]} Group"
        if gname in used_names:
            gname = f"{names[parent]} Group {gid.split('-')[-1]}"
        used_names.add(gname)
        for rank, bid in enumerate(order):
            if rank == 0:
                role, pct = "parent", 100.0
            else:
                affiliate = len(order) >= 4 and rng.random() < 0.22
                role = "affiliate" if affiliate else "subsidiary"
                pct = float(np.round(rng.uniform(20, 49.5), 1)) if affiliate else float(
                    np.round(rng.choice([51, 55, 60, 65, 70, 75, 80, 90, 100], p=[.08, .08, .12, .12, .12, .1, .14, .1, .14]), 1))
            members.append({"group_id": gid, "group_name": gname, "legacy_group_id": legacy,
                            "legacy_group_name": legacy_name, "borrower_id": bid, "role": role,
                            "ownership_pct": pct, "parent_borrower_id": parent})

    for (legacy, legacy_name), g in st.groupby(["group_id", "group_name"], sort=True):
        ids = g.sort_values("borrower_id").borrower_id.tolist()
        if len(ids) == 1:
            continue  # a stand-alone borrower: the book gives it a one-borrower "group"; there is nothing to connect
        if len(ids) < 12:
            new_group(legacy, legacy, legacy_name, ids, legacy_name)
            continue
        ordered = g.sort_values(["sub_sector", "region", "ead", "borrower_id"], ascending=[True, True, False, True])
        ids = ordered.borrower_id.tolist()
        pos = 0
        for n, k in enumerate(_chunks(len(ids), rng), 1):
            new_group(f"{legacy}-{n:03d}", legacy, legacy_name, ids[pos:pos + k], None)
            pos += k
    mem = pd.DataFrame(members).sort_values(["group_id", "borrower_id"]).reset_index(drop=True)
    gmap = mem.set_index("borrower_id")
    group_of = mem.groupby("borrower_id").group_id.first().to_dict()

    # ---------------------------------------------------------------- the supply chain
    rng = np.random.default_rng(rng_root + 2)
    rev = b.pivot_table(index="borrower_id", columns="reporting_quarter", values="revenue_sar_mn")
    ebit = b.pivot_table(index="borrower_id", columns="reporting_quarter", values="ebitda_sar_mn")
    purchases = 0.65 * (rev - ebit).clip(lower=1.0)
    by_sector = {s: g.sort_values("borrower_id") for s, g in st.groupby("sector")}
    weights_cache = {}
    supply: list[dict] = []
    for _, buyer in st.iterrows():
        k = int(np.clip(1 + rng.poisson(1.1 + 0.9 * (buyer.ead > st.ead.median())), 1, 5))
        options = SUPPLY[buyer.sector]
        sectors = [o[0] for o in options]
        sw = np.array([o[1] for o in options], dtype=float)
        picked: list[str] = []
        for _ in range(k):
            s = sectors[int(rng.choice(len(sectors), p=sw / sw.sum()))]
            cand = by_sector[s]
            key = (s, buyer.region)
            if key not in weights_cache:
                w = np.sqrt(cand.ead.to_numpy() + 1.0) * np.where(cand.region.to_numpy() == buyer.region, 1.8, 1.0)
                weights_cache[key] = w / w.sum()
            sid = str(cand.borrower_id.iloc[int(rng.choice(len(cand), p=weights_cache[key]))])
            if sid == buyer.borrower_id or sid in picked:
                continue
            if group_of.get(sid) and group_of.get(sid) == group_of.get(buyer.borrower_id) and rng.random() < 0.6:
                continue  # an intra-group sale is possible but not the norm
            picked.append(sid)
        if not picked:
            continue
        cover = rng.uniform(.25, .8)
        shares = rng.dirichlet(np.linspace(2.0, 0.8, len(picked))) * cover
        for sid, sh in zip(picked, shares):
            first = 0 if rng.random() < .68 else int(rng.integers(1, len(quarters) - 1))
            end = len(quarters) - 1 if rng.random() > .07 else int(rng.integers(first, len(quarters) - 1))
            supply.append({"supplier": sid, "buyer": buyer.borrower_id, "share": float(sh), "first": first, "last": end})
    sup = pd.DataFrame(supply)
    # a supplier sells at most 60% of its revenue (the largest buyer's cut), whatever the buyer's purchases were
    sup["value_max"] = [float((sup.share[i] * purchases.loc[sup.buyer[i]]).max() / rev.loc[sup.supplier[i]].min())
                        for i in range(len(sup))]
    sup["share"] = np.where(sup.value_max > .6, sup.share * .6 / sup.value_max, sup.share)
    sup = sup.sort_values(["supplier", "buyer"]).reset_index(drop=True)
    sup["edge_id"] = [f"ES{i + 1:06d}" for i in range(len(sup))]

    # ---------------------------------------------------------------- guarantees: only where the book has one
    rng = np.random.default_rng(rng_root + 3)
    guar_rows = col[col.collateral_type == "Corporate Guarantee"]
    gb = guar_rows.groupby("borrower_id").size().index.tolist()
    parent_of = mem[mem.role != "parent"].set_index("borrower_id").parent_borrower_id.to_dict()
    suppliers_of: dict[str, list[str]] = {}
    for r in sup.itertuples():
        suppliers_of.setdefault(r.buyer, []).append(r.supplier)
    guarantor: dict[str, tuple[str, str]] = {}
    for bid in gb:
        if bid in parent_of and rng.random() < .8:
            guarantor[bid] = (parent_of[bid], "group parent")
        else:
            peers = [p for p in suppliers_of.get(bid, []) if p != bid]
            if peers and rng.random() < .55:
                guarantor[bid] = (peers[int(rng.integers(len(peers)))], "supplier")
            else:
                pool = by_sector[st.set_index("borrower_id").loc[bid, "sector"]]
                big = pool[(pool.ead >= pool.ead.quantile(.7)) & (pool.borrower_id != bid)]
                if len(big):
                    guarantor[bid] = (str(big.borrower_id.iloc[int(rng.integers(len(big)))]), "sector peer")
    first_guar = guar_rows.groupby("borrower_id").reporting_quarter.min().to_dict()

    # ---------------------------------------------------------------- shared collateral inside groups
    rng = np.random.default_rng(rng_root + 4)
    real = col[col.collateral_type.isin(["Real Estate", "Plant and Equipment"]) & (col.reporting_quarter == last)]
    real_by_b = {k: g.sort_values("collateral_id") for k, g in real.groupby("borrower_id")}
    shared: list[dict] = []
    n_asset = 0
    for gid, g in mem.groupby("group_id", sort=True):
        if len(g) < 3 or rng.random() > .24:
            continue
        have = [bid for bid in g.borrower_id if bid in real_by_b]
        if len(have) < 2:
            continue
        pick = sorted(rng.choice(have, size=min(len(have), int(rng.integers(2, 4))), replace=False).tolist())
        rows = [real_by_b[bid].iloc[0] for bid in pick]
        ctype = rows[0].collateral_type
        mult = float(np.round(rng.uniform(.95, 1.45), 3))
        over = bool(rng.random() < .22)
        n_asset += 1
        for r in rows:
            shared.append({"collateral_id": f"SC{n_asset:05d}", "collateral_type": ctype, "borrower_id": r.borrower_id,
                           "facility_id": r.facility_id, "book_collateral_id": r.collateral_id,
                           "mult": mult, "over": over, "group_id": gid})
    sh = pd.DataFrame(shared).sort_values(["collateral_id", "borrower_id"]).reset_index(drop=True)

    # ---------------------------------------------------------------- persons
    rng = np.random.default_rng(rng_root + 5)
    persons: list[dict] = []
    pn = 0

    def person() -> tuple[str, str]:
        nonlocal pn
        pn += 1
        return f"PD{pn:05d}", f"{rng.choice(GIVEN)} {rng.choice(FAMILY)}"

    cross_pool = mem.borrower_id.tolist()
    for gid, g in mem.groupby("group_id", sort=True):
        parent = g[g.role == "parent"].borrower_id.iloc[0]
        subs = g[g.role != "parent"].borrower_id.tolist()
        owner_id, owner_name = person()
        if rng.random() < .45:
            co_id, co_name = person()
            persons += [{"person_id": owner_id, "person_name": owner_name, "borrower_id": parent, "role": "Owner",
                         "ownership_pct": float(np.round(rng.uniform(51, 70), 1))},
                        {"person_id": co_id, "person_name": co_name, "borrower_id": parent, "role": "Owner",
                         "ownership_pct": float(np.round(rng.uniform(15, 30), 1))}]
        else:
            persons.append({"person_id": owner_id, "person_name": owner_name, "borrower_id": parent, "role": "Owner",
                            "ownership_pct": float(np.round(rng.uniform(60, 100), 1))})
        persons.append({"person_id": owner_id, "person_name": owner_name, "borrower_id": parent, "role": "Chairman",
                        "ownership_pct": None})
        for bid in subs:
            if rng.random() < .8:
                persons.append({"person_id": owner_id, "person_name": owner_name, "borrower_id": bid,
                                "role": "Director", "ownership_pct": None})
            ceo_id, ceo_name = person()
            persons.append({"person_id": ceo_id, "person_name": ceo_name, "borrower_id": bid, "role": "CEO",
                            "ownership_pct": None})
    # a few directors who sit on the boards of unrelated companies in one sector
    k_cross = int(.03 * len(st))
    pool = st.sort_values("borrower_id")
    for _ in range(k_cross):
        s = str(rng.choice(sorted(by_sector)))
        cand = by_sector[s].borrower_id.tolist()
        if len(cand) < 2:
            continue
        a, c = rng.choice(len(cand), size=2, replace=False)
        pid, pname = person()
        for idx in (a, c):
            persons.append({"person_id": pid, "person_name": pname, "borrower_id": cand[int(idx)], "role": "Director",
                            "ownership_pct": None})
    per = pd.DataFrame(persons).drop_duplicates(["person_id", "borrower_id", "role"])
    per = per.sort_values(["person_id", "borrower_id", "role"]).reset_index(drop=True)
    per["valid_from_quarter"] = quarters[0]
    per["valid_to_quarter"] = None

    # ---------------------------------------------------------------- per quarter
    q_rows = []
    qmem = []
    ead_f = f.set_index(["facility_id", "reporting_quarter"]).ead_sar_mn
    for q in quarters:
        i = qi[q]
        g = mem.copy()
        g["tenant_id"] = tenant
        g["reporting_quarter"] = q
        qmem.append(g)
    group_q = pd.concat(qmem, ignore_index=True)[["tenant_id", "reporting_quarter", "group_id", "group_name",
                                                  "legacy_group_id", "legacy_group_name", "borrower_id", "role",
                                                  "ownership_pct", "parent_borrower_id"]]

    edges: list[pd.DataFrame] = []
    # GROUP edges (parent -> member)
    ge = mem[mem.role != "parent"][["parent_borrower_id", "borrower_id", "ownership_pct", "role", "group_id"]].copy()
    ge = ge.sort_values(["group_id", "borrower_id"]).reset_index(drop=True)
    ge["edge_id"] = [f"EG{i + 1:06d}" for i in range(len(ge))]
    for q in quarters:
        e = pd.DataFrame({"tenant_id": tenant, "reporting_quarter": q, "edge_id": ge.edge_id, "rel_type": "GROUP",
                          "source_borrower_id": ge.parent_borrower_id, "target_borrower_id": ge.borrower_id,
                          "ownership_pct": ge.ownership_pct, "relation_detail": ge.role,
                          "group_id": ge.group_id})
        edges.append(e)
    # SUPPLIES edges
    rngv = np.random.default_rng(rng_root + 6)
    for q in quarters:
        i = qi[q]
        live = sup[(sup["first"] <= i) & (sup["last"] >= i)]
        pv = np.array([purchases.at[b_, q] for b_ in live.buyer])
        rv = np.array([rev.at[s_, q] for s_ in live.supplier])
        value = live.share.to_numpy() * pv
        e = pd.DataFrame({"tenant_id": tenant, "reporting_quarter": q, "edge_id": live.edge_id.to_numpy(),
                          "rel_type": "SUPPLIES", "source_borrower_id": live.supplier.to_numpy(),
                          "target_borrower_id": live.buyer.to_numpy(),
                          "purchase_share_pct": np.round(100 * live.share.to_numpy(), 2),
                          "revenue_share_pct": np.round(100 * value / rv, 2),
                          "annual_value_sar_mn": np.round(value, 4)})
        edges.append(e)
    # GUARANTEES: the book's own Corporate Guarantee collateral rows
    gtab = pd.DataFrame([{"borrower_id": k, "guarantor": v[0], "basis": v[1]} for k, v in sorted(guarantor.items())])
    gtab["edge_id"] = [f"EU{i + 1:06d}" for i in range(len(gtab))]
    gq = guar_rows.merge(gtab, on="borrower_id")
    gq = gq.sort_values(["reporting_quarter", "facility_id"])
    edges.append(pd.DataFrame({"tenant_id": tenant, "reporting_quarter": gq.reporting_quarter.to_numpy(),
                               "edge_id": gq.edge_id.to_numpy(), "rel_type": "GUARANTEES",
                               "source_borrower_id": gq.guarantor.to_numpy(), "target_borrower_id": gq.borrower_id.to_numpy(),
                               "facility_id": gq.facility_id.to_numpy(), "book_collateral_id": gq.collateral_id.to_numpy(),
                               "guarantee_amount_sar_mn": gq.allocated_value_sar_mn.round(4).to_numpy(),
                               "relation_detail": gq.basis.to_numpy()}))
    # SHARES_COLLATERAL: pairs of borrowers claiming the same asset
    pairs = []
    for cid, g in sh.groupby("collateral_id", sort=True):
        ids = g.borrower_id.tolist()
        for a in range(len(ids)):
            for c in range(a + 1, len(ids)):
                pairs.append({"collateral_id": cid, "a": ids[a], "b": ids[c]})
    pr = pd.DataFrame(pairs)
    pr["edge_id"] = [f"EC{i + 1:06d}" for i in range(len(pr))]
    for q in quarters:
        edges.append(pd.DataFrame({"tenant_id": tenant, "reporting_quarter": q, "edge_id": pr.edge_id,
                                   "rel_type": "SHARES_COLLATERAL", "source_borrower_id": pr.a,
                                   "target_borrower_id": pr.b, "collateral_id": pr.collateral_id}))
    edge_q = pd.concat(edges, ignore_index=True)
    for c in ("ownership_pct", "purchase_share_pct", "revenue_share_pct", "annual_value_sar_mn",
              "guarantee_amount_sar_mn"):
        if c not in edge_q:
            edge_q[c] = np.nan
    for c in ("relation_detail", "group_id", "facility_id", "book_collateral_id", "collateral_id"):
        if c not in edge_q:
            edge_q[c] = None
    edge_q = edge_q[["tenant_id", "reporting_quarter", "edge_id", "rel_type", "source_borrower_id", "target_borrower_id",
                     "relation_detail", "group_id", "ownership_pct", "purchase_share_pct", "revenue_share_pct",
                     "annual_value_sar_mn", "facility_id", "book_collateral_id", "guarantee_amount_sar_mn",
                     "collateral_id"]]
    edge_q = edge_q.sort_values(["reporting_quarter", "rel_type", "edge_id"]).reset_index(drop=True)

    # a shared asset's claims follow the borrowers' own collateral rows, quarter by quarter: each claimant claims its
    # own allocated value (x1.35 on an over-pledged asset); the asset is worth the claimants' values times a multiple
    bookc = col.set_index(["collateral_id", "reporting_quarter"]).allocated_value_sar_mn
    claimants = sh.groupby("collateral_id").size()
    parts = []
    for q in quarters:
        x = sh.assign(tenant_id=tenant, reporting_quarter=q)
        x["alloc"] = [bookc.get((cid, q), np.nan) for cid in x.book_collateral_id]
        x = x.dropna(subset=["alloc"])
        x = x[x.groupby("collateral_id").alloc.transform("size") == x.collateral_id.map(claimants)]
        parts.append(x)
    shq = pd.concat(parts, ignore_index=True)
    shq["market_value_sar_mn"] = (shq.groupby(["reporting_quarter", "collateral_id"]).alloc.transform("sum") * shq.mult).round(4)
    shq["claim_sar_mn"] = (shq.alloc * np.where(shq.over, 1.35, 1.0)).round(4)
    shq["allocation_pct"] = np.round(100 * shq.claim_sar_mn / shq.market_value_sar_mn, 2)
    shq = shq[["tenant_id", "reporting_quarter", "collateral_id", "collateral_type", "borrower_id", "facility_id",
               "book_collateral_id", "market_value_sar_mn", "claim_sar_mn", "allocation_pct", "group_id"]]
    shq = shq.sort_values(["reporting_quarter", "collateral_id", "borrower_id"]).reset_index(drop=True)
    per.insert(0, "tenant_id", tenant)
    return {"rel_group_quarter": group_q, "rel_edge_quarter": edge_q, "rel_person_role": per,
            "rel_shared_collateral": shq}


def retail(rng_root: int) -> dict[str, pd.DataFrame]:
    src = SOURCE_LAKE / RET_SRC
    c = pd.read_parquet(src / "retail_customer_month.parquet",
                        columns=["tenant_id", "customer_id", "reporting_month", "region", "employment_type",
                                 "customer_segment"])
    corp = pd.read_parquet(SOURCE_LAKE / CORP_SRC / "corp_borrower_quarter.parquet",
                           columns=["borrower_id", "region", "reporting_quarter"])
    corp = corp[corp.reporting_quarter == corp.reporting_quarter.max()].sort_values("borrower_id")
    fac = pd.read_parquet(SOURCE_LAKE / CORP_SRC / "corp_facility_quarter.parquet",
                          columns=["borrower_id", "reporting_quarter", "ead_sar_mn"])
    ead = fac[fac.reporting_quarter == fac.reporting_quarter.max()].groupby("borrower_id").ead_sar_mn.sum()
    last = c.reporting_month.max()
    cust = c[c.reporting_month == last].sort_values("customer_id").reset_index(drop=True)
    rng = np.random.default_rng(rng_root + 11)

    # households: about one customer in eight lives with one to three others in the same region
    hh_rows = []
    hid = 0
    for region, g in cust.groupby("region", sort=True):
        ids = g.customer_id.tolist()
        rng.shuffle(ids)
        pos = 0
        n_hh = int(.055 * len(ids))
        for _ in range(n_hh):
            k = int(rng.choice([2, 3, 4], p=[.55, .3, .15]))
            members = ids[pos:pos + k]
            pos += k
            if len(members) < 2:
                break
            hid += 1
            roles = ["head", "spouse"] + ["dependant"] * (k - 2)
            for m, r in zip(members, roles):
                hh_rows.append({"household_id": f"HH{hid:06d}", "customer_id": m, "role": r})
    hh = pd.DataFrame(hh_rows).sort_values(["household_id", "customer_id"]).reset_index(drop=True)

    # employers: salaried customers are employed by a corporate borrower in their region (government salaried: none)
    salaried = cust[cust.employment_type == "Salaried-Private"]
    emp_rows = []
    for region, g in salaried.groupby("region", sort=True):
        # The retail book's regions are not the corporate book's: match by name where they coincide, else any.
        pool = corp[corp.region == region]
        if pool.empty:
            pool = corp
        w = np.sqrt(ead.reindex(pool.borrower_id).fillna(1.0).to_numpy())
        w = w / w.sum()
        pick = rng.choice(len(pool), size=len(g), p=w)
        for cid, p in zip(g.customer_id, pick):
            if rng.random() < .78:
                emp_rows.append({"customer_id": cid, "employer_borrower_id": str(pool.borrower_id.iloc[int(p)])})
    emp = pd.DataFrame(emp_rows).sort_values("customer_id").reset_index(drop=True)

    def monthly(frame: pd.DataFrame, tenant: str) -> pd.DataFrame:
        m = c[["tenant_id", "customer_id", "reporting_month"]].merge(frame, on="customer_id", how="inner")
        return m.sort_values(["reporting_month", "customer_id"]).reset_index(drop=True)

    return {"rel_household_month": monthly(hh, ""), "rel_employer_month": monthly(emp, "")}


