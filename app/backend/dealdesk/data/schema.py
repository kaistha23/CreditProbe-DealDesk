def _long(name: str, d: str) -> str:
    d = _SHORT.get(d, d)
    return d if len(d) > 12 else f"{d.rstrip('.')} ({name.replace('_', ' ')})."


def columns(relation: str) -> list[C]:
    """All columns of a relation, its own followed by the lineage columns (descriptions always a full phrase)."""
    return [(n, t, u, _long(n, d)) for n, t, u, d in list(RELATIONS[relation]["columns"]) + LINEAGE]


def column_names(relation: str) -> list[str]:
    return [c[0] for c in columns(relation)]


def dictionary(folder: str) -> dict[str, dict[str, str]]:
    """{column: {type, unit, description}} for every column of the relations in one folder (first definition wins)."""
    out: dict[str, dict[str, str]] = {}
    for rid, spec in RELATIONS.items():
        if spec["folder"] != folder:
            continue
        for n, t, u, d in columns(rid):
            out.setdefault(n, {"type": t, "unit": u, "description": d})
    return out


