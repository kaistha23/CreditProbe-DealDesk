_RW = {**{r: 20 for r in RATING_ORDER[:4]}, **{r: 50 for r in RATING_ORDER[4:7]},
       **{r: 100 for r in RATING_ORDER[7:13]}, **{r: 150 for r in RATING_ORDER[13:]}}
_RET_RW = {"Mortgage": 35, "Personal Finance": 75, "Credit Card": 75, "Auto Finance": 75, "Buy Now Pay Later": 75}


def collateral(d: dict, X: pd.DataFrame, cls: pd.DataFrame) -> dict[str, pd.DataFrame]:
    rng = _rng(5)
    COL, RCOL = d["COL"], d["RCOL"]
    vd_c = (pd.Period(d["cq"], "Q") - COL.valuation_age_quarters.fillna(0).astype(int)).astype(str)
    vd_c = [f"{_q_end_month(q)}-28" for q in vd_c]
    reg_c = np.where(rng.random(len(COL)) < 0.93, "Registered", np.where(rng.random(len(COL)) < 0.6, "Pending", "Not registered"))
    ci = pd.DataFrame({"book": "corporate", "collateral_id": COL.collateral_id, "exposure_id": COL.facility_id,
                       "obligor_id": COL.borrower_id, "type": COL.collateral_type,
                       "value_sar_mn": COL.market_value_sar_mn.round(4), "haircut_pct": COL.haircut_pct.round(2),
                       "valuation_date": vd_c, "registration_status": reg_c})
    vd_r = [f"{_add_months(d['rm'], -int(a))}-28" for a in RCOL.valuation_age_months.fillna(0)]
    hc = RCOL.collateral_type.map({"Residential Property": 20.0, "Motor Vehicle": 35.0}).fillna(30.0)
    ri = pd.DataFrame({"book": "retail", "collateral_id": "RK" + RCOL.account_id.str[2:], "exposure_id": RCOL.account_id,
                       "obligor_id": RCOL.customer_id, "type": RCOL.collateral_type,
                       "value_sar_mn": RCOL.collateral_value_sar_mn.round(4), "haircut_pct": hc,
                       "valuation_date": vd_r,
                       "registration_status": np.where(rng.random(len(RCOL)) < 0.97, "Registered", "Pending")})
    col_item = pd.concat([ci, ri], ignore_index=True).sort_values("collateral_id").reset_index(drop=True)
    # guarantees: the relationship domain's GUARANTEES edges at the as-of (guarantor -> guaranteed borrower)
    g = d["ED"][d["ED"].rel_type == "GUARANTEES"]
    names = d["B"].set_index("borrower_id").borrower_name
    perf = rng.random(len(g))
    col_guarantee = pd.DataFrame({
        "book": "corporate", "guarantee_id": "GT" + g.edge_id.str[2:].to_numpy(),
        "exposure_id": g.facility_id.to_numpy(), "obligor_id": g.target_borrower_id.to_numpy(),
        "guarantor_name": g.source_borrower_id.map(names).to_numpy(), "guarantor_cif": g.source_borrower_id.to_numpy(),
        "guarantor_type": "Corporate", "amount_sar_mn": g.guarantee_amount_sar_mn.round(4).to_numpy(),
        "perfected": (perf < 0.9).astype(int)}).sort_values("guarantee_id").reset_index(drop=True)
    rs = cls[cls.restructured_flag == 1]
    col_restructured = pd.DataFrame({
        "book": rs.book, "exposure_id": rs.exposure_id, "obligor_id": rs.obligor_id,
        "restructure_date": [f"{_add_months(m, -int(k))}-15" for m, k in
                             zip(np.where(rs.book == "corporate", _q_end_month(d["cq"]), d["rm"]),
                                 rng.integers(1, 18, len(rs)))],
        "restructure_type": rs.restructure_type, "count_24m": np.maximum(1, rs.deferrals_24m // 2),
        "probation_end": rs.probation_end,
        "status": np.where(rs.stage == 3, "Non-performing", np.where(rs.stage == 2, "Probation", "Cured"))}).reset_index(drop=True)
    # related-party register: group members (economic groups) and staff links
    RG = d["RG"]
    ead_b = X[X.book == "corporate"].groupby("obligor_id").ead.sum()
    rp = RG[RG.borrower_id != RG.parent_borrower_id].dropna(subset=["parent_borrower_id"])
    col_rp1 = pd.DataFrame({"book": "corporate", "obligor_id": rp.borrower_id, "party_name": rp.parent_borrower_id.map(names),
                            "party_cif": rp.parent_borrower_id, "relation": "Parent / " + rp.role.astype(str),
                            "exposure_sar_mn": rp.parent_borrower_id.map(ead_b).round(4)})
    staff = d["staff"]
    col_rp2 = pd.DataFrame({"book": "corporate", "obligor_id": staff.obligor_id, "party_name": staff.person_name,
                            "party_cif": staff.person_id, "relation": "Bank staff: " + staff.role,
                            "exposure_sar_mn": staff.obligor_id.map(ead_b).round(4)})
    col_related_party = pd.concat([col_rp1, col_rp2], ignore_index=True).sort_values(
        ["obligor_id", "party_cif"]).reset_index(drop=True)
    # CRWA per exposure (standardised-style weights; eligible collateral after haircut)
    colv = col_item.assign(net=col_item.value_sar_mn * (1 - col_item.haircut_pct / 100)).groupby("exposure_id").net.sum()
    crm = np.minimum(X.exposure_id.map(colv).fillna(0).to_numpy(), X.ead.to_numpy())
    rw = np.where(X.book == "corporate", X.rating.map(_RW).fillna(100).to_numpy(),
                  X["product"].map(_RET_RW).fillna(75).to_numpy())
    rw = np.where(X.stage.to_numpy() == 3, np.maximum(rw, 150), rw)
    col_crwa = pd.DataFrame({"book": X.book, "exposure_id": X.exposure_id, "obligor_id": X.obligor_id,
                             "ead_sar_mn": X.ead.round(4), "crm_sar_mn": np.round(crm, 4), "risk_weight_pct": rw,
                             "crwa_sar_mn": np.round((X.ead.to_numpy() - crm) * rw / 100, 4)})
    # large exposures by economic group (the relationship domain's carved groups)
    tier1 = float(np.round(col_crwa.crwa_sar_mn.sum() * 0.17, 4))   # capital base = 17% of CRWA (data_loader.CAPITAL_RATIO)
    m = RG[["group_id", "group_name", "borrower_id"]].drop_duplicates("borrower_id")
    m = m.assign(ead=m.borrower_id.map(ead_b).fillna(0))
    le = m.groupby(["group_id", "group_name"]).agg(members=("borrower_id", "count"), ead_sar_mn=("ead", "sum")).reset_index()
    le["tier1_capital_sar_mn"] = tier1
    le["pct_of_capital"] = (100 * le.ead_sar_mn / tier1).round(2)
    le["limit_pct"] = 25.0
    le["large_exposure"] = (le.pct_of_capital >= 10).astype(int)
    le["breach"] = (le.pct_of_capital > le.limit_pct).astype(int)
    le["ead_sar_mn"] = le.ead_sar_mn.round(4)
    col_large_exposure = le.sort_values("ead_sar_mn", ascending=False).reset_index(drop=True)
    return {"col_item": col_item, "col_guarantee": col_guarantee, "col_restructured": col_restructured,
            "col_related_party": col_related_party, "col_large_exposure": col_large_exposure, "col_crwa": col_crwa}


