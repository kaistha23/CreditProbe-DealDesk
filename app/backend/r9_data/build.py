# ----------------------------------------------------------------------------- origination
def origination(d: dict, X: pd.DataFrame, col_by_exp: pd.Series) -> pd.DataFrame:
    rng = _rng(3)
    n = len(X)
    corp = (X.book == "corporate").to_numpy()
    orig_date = np.where(corp, X.orig.astype(str).str[:4] + "-" +
                         (X.orig.astype(str).str[-1].replace({"Q": "1"}).map(lambda q: f"{(int(q) - 1) * 3 + 1:02d}" if q.isdigit() else "01")) + "-15",
                         X.orig.astype(str) + "-15")
    rating_o = np.where(corp, X.rating_orig.fillna(X.rating).astype(str), X.rating.astype(str))
    pd_o = np.where(corp, pd.Series(rating_o).map(RATING_PD).fillna(1.0).to_numpy(),
                    np.round(X.pd.to_numpy() * 100 * (0.5 + 0.4 * rng.random(n)), 4))
    margin = np.where(corp, 1.25 + 0.35 * np.log1p(pd_o) + 0.8 * rng.random(n), 2.5 + 4 * rng.random(n))
    ftp = 4.6 + 0.9 * rng.random(n)
    tenor_map = {"term_loan": 60, "project_finance": 96, "working_capital": 12, "trade_finance": 6,
                 "supply_chain_finance": 6, "revolving_credit": 36, "overdraft": 12, "asset_finance": 48,
                 "Mortgage": 240, "Personal Finance": 60, "Credit Card": 12, "Auto Finance": 60, "Buy Now Pay Later": 3}
    tenor = X["product"].map(tenor_map).fillna(36).to_numpy() * np.where(rng.random(n) < 0.3, 0.5, 1.0)
    lim0 = X.limit.to_numpy() * (0.9 + 0.2 * rng.random(n))
    return pd.DataFrame({
        "book": X.book, "exposure_id": X.exposure_id, "obligor_id": X.obligor_id, "orig_date": orig_date,
        "orig_margin_pct": np.round(margin, 2),
        "orig_fees_sar_mn": np.round(lim0 * np.where(corp, 0.0035 + 0.006 * rng.random(n), 0.005), 4),
        "orig_rating": rating_o, "orig_pd_pct": np.round(pd_o, 4), "ftp_pct": np.round(ftp, 2),
        "tenor_months": tenor.astype(int),
        "orig_collateral_sar_mn": np.round(col_by_exp.reindex(X.exposure_id).fillna(0).to_numpy() *
                                           (0.95 + 0.15 * rng.random(n)), 4),
        "hurdle_rate_pct": np.where(corp, np.where(X.rating.isin(RATING_ORDER[:10]), 12.0, 14.0), 15.0),
        "orig_limit_sar_mn": np.round(lim0, 4),
    })


# ----------------------------------------------------------------------------- classification
def classification(d: dict, X: pd.DataFrame) -> dict[str, pd.DataFrame]:
    rng = _rng(4)
    cl = _crm_clauses()
    n = len(X)
    corp = (X.book == "corporate").to_numpy()
    prev = pd.concat([d["Fp"].set_index("facility_id").stage, d["Ap"].set_index("account_id").stage])
    prev_stage = X.exposure_id.map(prev).fillna(X.stage).astype(int).to_numpy()
    dpd = X.dpd.to_numpy()
    bucket = np.select([dpd <= 0, dpd <= 30, dpd <= 60, dpd <= 90], ["Current", "1-30", "31-60", "61-90"], "90+")
    stage = X.stage.to_numpy()
    defer = np.where(stage >= 2, rng.choice([0, 1, 2, 3, 4], n, p=[0.45, 0.2, 0.15, 0.12, 0.08]),
                     rng.choice([0, 1, 2], n, p=[0.9, 0.08, 0.02]))
    cv = d["CV"]
    cov_breach = cv[cv.breach_flag == 1].groupby("facility_id").covenant_type.first()
    ews = pd.concat([d["ews_c"], d["ews_r"]])
    band = X.exposure_id.map(ews.ews_band).fillna("low").to_numpy()
    sig = X.exposure_id.map(ews.ews_reasons).fillna("").to_numpy()
    asof_c, asof_r = d["cq"], d["rm"]
    src_date = np.where(corp, _q_end_month(asof_c) + "-30", d["rm"] + "-28")
    reasons: list[tuple] = []

    def add(mask, kind, code, text, number, sub, source):
        for j in np.flatnonzero(mask):
            reasons.append((X.book.iat[j], X.exposure_id.iat[j], X.obligor_id.iat[j], kind, code, text,
                            f"{number}{sub}", cl[number], source, src_date[j]))

    r = rng.random((n, 8))
    # a few performing corporate facilities with 3 deferrals in 24 months still in Stage 1 (the Art 7.7 finding)
    defer = np.where(corp & (stage == 1) & (rng.random(n) < 0.004), 3, defer)
    s2 = stage >= 2
    notch = X.notches.fillna(0).to_numpy()
    sector_stress = X.sector.isin(["Construction", "Real Estate"]).to_numpy()
    # SICR indicators (evidence present; sicr_flag stays the book's flag)
    add(dpd > 30, "SICR", "SICR-DPD30", "Repayments more than 30 days past due", "7.8", "", "book")
    add(defer >= 3, "SICR", "SICR-DEFER3", "3 or more deferrals in a rolling 24 months", "7.7", "", "deferral register")
    add(corp & (notch < 0), "SICR", "SICR-DOWNGRADE", "Rating downgraded since last review", "7.11", "(e)", "ratings")
    add(corp & X.exposure_id.isin(cov_breach.index).to_numpy(), "SICR", "SICR-COVENANT",
        "Financial covenant breached", "7.11", "(a)", "covenant monitoring")
    add(corp & s2 & (r[:, 0] < 0.12), "SICR", "SICR-QUALAUDIT", "Qualified report by external auditors", "7.11", "(f)(ii)",
        "financial statements")
    add(corp & s2 & (r[:, 1] < 0.18), "SICR", "SICR-LATEFIN", "Financial statements late or withheld", "7.11", "(f)(i)",
        "financial statements")
    add(corp & s2 & (r[:, 2] < 0.08), "SICR", "SICR-PARENT", "Majority-owning parent under stress", "7.11", "(h)",
        "group register")
    add(corp & s2 & (r[:, 3] < 0.06), "SICR", "SICR-LITIGATION", "Pending litigation with detrimental impact", "7.11",
        "(f)(iv)", "legal register")
    add(corp & s2 & (r[:, 4] < 0.05), "SICR", "SICR-MGMT", "Sudden management change", "7.11", "(d)", "KYC review")
    add(corp & s2 & sector_stress & (r[:, 5] < 0.35), "SICR", "SICR-SECTOR", "Sector under macroeconomic stress", "7.12",
        "", "sector outlook")
    add(~corp & s2 & (r[:, 2] < 0.35), "SICR", "SICR-SCORE", "Behaviour score band deteriorated", "7.11", "(e)",
        "behaviour score")
    # UTP indicators
    s3 = stage == 3
    od = (X["product"] == "overdraft").to_numpy()
    add(corp & od & ((dpd > 90) | (s3 & (r[:, 6] < 0.6))), "UTP", "UTP-HARDCORE-OD", "Hardcore overdraft above limit for more than 90 days",
        "6.5", "", "deposits")
    add(corp & s3 & (r[:, 0] < 0.08), "UTP", "UTP-OWNER-ABSENT", "Owner outside the UAE for more than 6 months", "6.8",
        "(j)", "KYC review")
    add(corp & s3 & (r[:, 1] < 0.3), "UTP", "UTP-COVENANT", "Material covenant breached", "6.9", "(d)", "covenant monitoring")
    add(corp & s3 & (X.restr_book.fillna(0).to_numpy() == 1), "UTP", "UTP-RESTRUCTURE", "Repeated restructuring",
        "6.9", "(e)", "restructured register")
    add(corp & s3 & (r[:, 2] < 0.15), "UTP", "UTP-CROSSDEFAULT", "Default of another group member", "6.12", "",
        "group register")
    add(s3 & (r[:, 3] < 0.2), "UTP", "UTP-OTHERBANK", "Classified as defaulted by another bank", "6.8", "(e)", "bureau")
    add(dpd > 90, "UTP", "UTP-DPD90", "Past due more than 90 days", "6.8", "(b)", "book")
    cls_reason = pd.DataFrame(reasons, columns=["book", "exposure_id", "obligor_id", "kind", "code", "text", "article",
                                                "clause_id", "source_dataset", "source_date"])
    cls_reason = cls_reason.sort_values(["exposure_id", "kind", "code"]).reset_index(drop=True)
    pack = lambda g: json.dumps(g[["code", "text", "article", "clause_id", "source_dataset", "source_date"]].to_dict("records"))  # noqa: E731
    sicr_j = cls_reason[cls_reason.kind == "SICR"].groupby("exposure_id").apply(pack, include_groups=False)
    utp_j = cls_reason[cls_reason.kind == "UTP"].groupby("exposure_id").apply(pack, include_groups=False)
    restr = (X.restr_book.fillna(0).to_numpy() == 1) | (defer >= 3) & (stage >= 2)
    rtype = np.where(restr, np.where(stage >= 2, "distressed", "non-distressed"), None)
    asof_m = np.where(corp, _q_end_month(asof_c), asof_r)
    prob_end = [(_add_months(m, 12 if t == "distressed" else 6) if t else None) for m, t in zip(asof_m, rtype)]
    watch = np.where(X.watch_book.fillna(0).to_numpy() == 1, "Bank Watchlist",
                     np.where(corp & (stage == 1) & np.isin(band, ["moderate", "high", "critical"]) & (r[:, 7] < 0.15),
                              "Accepted Risk Watch", "None"))
    cls = pd.DataFrame({
        "book": X.book, "exposure_id": X.exposure_id, "obligor_id": X.obligor_id,
        "period": np.where(corp, asof_c, asof_r), "stage": stage, "previous_stage": prev_stage, "dpd_days": dpd,
        "dpd_bucket": bucket, "deferrals_24m": defer, "sicr_flag": X.sicr_book.astype(int),
        "sicr_reasons": X.exposure_id.map(sicr_j).fillna("[]"),
        "utp_flag": ((stage == 3) | (X.default_book == 1)).astype(int),
        "utp_reasons": X.exposure_id.map(utp_j).fillna("[]"),
        "ews_bucket": band, "ews_signals": [json.dumps([x for x in s.split("; ") if x]) for s in sig],
        "watch_status": watch, "restructured_flag": restr.astype(int), "restructure_type": rtype,
        "probation_end": prob_end,
    })
    return {"cls_exposure": cls, "cls_reason": cls_reason}


