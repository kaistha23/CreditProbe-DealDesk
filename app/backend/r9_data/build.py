def build() -> dict[str, pd.DataFrame]:
    d = load_books()
    d["staff"] = staff_links(d)
    o = obligors(d)
    X = exposures(d)
    out: dict[str, pd.DataFrame] = {}
    out.update(deposits(d, o))
    colv = pd.concat([d["COL"].groupby("facility_id").market_value_sar_mn.sum(),
                      d["RCOL"].set_index("account_id").collateral_value_sar_mn])
    out["orig_facility"] = origination(d, X, colv)
    out.update(classification(d, X))
    out.update(collateral(d, X, out["cls_exposure"]))
    out.update(relationships(d, out["dep_counterparty"]))
    out.update(ecl_runs(d))
    out["_asof"] = pd.DataFrame([{"corporate": d["cq"], "retail": d["rm"]}])
    return out


def _sha(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    out = build()
    asof = out.pop("_asof").iloc[0].to_dict()
    dates = {"corporate": str(pd.Period(asof["corporate"], "Q").end_time.date()),
             "retail": str(pd.Period(asof["retail"], "M").end_time.date())}
    rd = release_dir()
    rd.mkdir(parents=True, exist_ok=True)
    rels = {}
    for dom, tables in DOMAIN_TABLES.items():
        for t in tables:
            f = out[t].reset_index(drop=True)
            if "as_of_date" not in f.columns:
                bk = f["book"] if "book" in f.columns else pd.Series("corporate", index=f.index)
                f["as_of_date"] = bk.map(dates).fillna(dates["corporate"])
            p = rd / f"{t}.parquet"
            f.to_parquet(p, index=False, compression="zstd")
            rels[t] = {"domain": dom, "file": p.name, "rows": int(len(f)), "columns": list(f.columns), "sha256": _sha(p)}
    man = {"release_id": RELEASE, "builder": "backend/r9_data/build.py", "seed": SEED, "as_of": asof,
           "ecl_runs": {"current": RUN_CURRENT, "prior": RUN_PRIOR}, "provenance": PROVENANCE,
           "domains": DOMAIN_TABLES, "relations": rels, "dictionary": DICTIONARY}
    (rd / "manifest.json").write_text(json.dumps(man, indent=1, ensure_ascii=False) + "\n")
    for t, r in rels.items():
        print(f"{t:22s} {r['rows']:>9,d}")


if __name__ == "__main__":
    main()
