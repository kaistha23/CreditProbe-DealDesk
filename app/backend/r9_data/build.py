def _run_frame(run_id: str, F: pd.DataFrame, A: pd.DataFrame, B: pd.DataFrame, colv: pd.Series,
               cq: str, rm: str) -> pd.DataFrame:
    rat = B.set_index("borrower_id").rating_current
    c = pd.DataFrame({"run_id": run_id, "book": "corporate", "exposure_id": F.facility_id, "obligor_id": F.borrower_id,
                      "book_period": cq, "ead_sar_mn": F.ead_sar_mn, "limit_sar_mn": F.limit_sar_mn,
                      "pd_12m_pct": F.pd_pit_12m * 100, "pd_lifetime_pct": F.pd_lifetime * 100, "lgd_pct": F.lgd_pct,
                      "stage": F.stage, "dpd_days": F.dpd_days, "rating": F.borrower_id.map(rat),
                      "sector": F.sector, "ecl_sar_mn": F.ecl_sar_mn})
    a = pd.DataFrame({"run_id": run_id, "book": "retail", "exposure_id": A.account_id, "obligor_id": A.customer_id,
                      "book_period": rm, "ead_sar_mn": A.ead_sar_mn, "limit_sar_mn": A.limit_sar_mn,
                      "pd_12m_pct": A.pd_pit_12m * 100, "pd_lifetime_pct": A.pd_lifetime * 100, "lgd_pct": A.lgd_pct,
                      "stage": A.stage, "dpd_days": A.dpd_days, "rating": A.score_band, "sector": A["product"],
                      "ecl_sar_mn": A.ecl_sar_mn})
    x = pd.concat([c, a], ignore_index=True)
    x["collateral_sar_mn"] = x.exposure_id.map(colv).round(4)
    x["overlay_sar_mn"] = np.where(x.sector.isin(["Construction", "Real Estate"]), x.ecl_sar_mn * 0.05, 0.0)
    w = x.ecl_sar_mn - x.overlay_sar_mn
    base = w / _K
    x["ecl_base_sar_mn"] = base
    x["ecl_upside_sar_mn"] = base * _MULT["upside"]
    x["ecl_downside_sar_mn"] = base * _MULT["downside"]
    x["ecl_weighted_sar_mn"] = w
    return x


_RUN_COLS = ["run_id", "book", "exposure_id", "obligor_id", "book_period", "ead_sar_mn", "limit_sar_mn", "pd_12m_pct",
             "pd_lifetime_pct", "lgd_pct", "stage", "dpd_days", "rating", "collateral_sar_mn", "ecl_base_sar_mn",
             "ecl_upside_sar_mn", "ecl_downside_sar_mn", "ecl_weighted_sar_mn", "overlay_sar_mn", "ecl_sar_mn"]


def ecl_runs(d: dict) -> dict[str, pd.DataFrame]:
    colv_c = d["COL"].groupby("facility_id").market_value_sar_mn.sum()
    colv_cp = d["COLp"].groupby("facility_id").market_value_sar_mn.sum()
    colv_r = d["RCOL"].set_index("account_id").collateral_value_sar_mn
    colv_rp = d["RCOLp"].set_index("account_id").collateral_value_sar_mn
    cur = _run_frame(RUN_CURRENT, d["F"], d["A"], d["B"], pd.concat([colv_c, colv_r]), d["cq"], d["rm"])
    pri = _run_frame(RUN_PRIOR, d["Fp"], d["Ap"], d["Bp"], pd.concat([colv_cp, colv_rp]), d["cp"], d["rp"])
    pri_i = pri.set_index("exposure_id")
    cur_i = cur.set_index("exposure_id")
    common = cur_i.index.intersection(pri_i.index)
    an: list[dict] = []

    def pick(mask: pd.Series, k: int = 0) -> str:
        ids = mask[mask].index
        ids = [i for i in ids if i in common and i not in {a["exposure_id"] for a in an}]
        return sorted(ids)[(k * 7919 + len(an) * 3571 + 1009) % max(len(ids), 1)]

    def note(i, run, kind, field, pv, cv, exp, rerun, txt):
        an.append({"anomaly_id": f"AN{len(an) + 1:02d}", "run_id": run, "book": cur_i.at[i, "book"], "exposure_id": i,
                   "kind": kind, "field": field, "prior_value": pv, "current_value": cv, "expected": exp,
                   "rerun_required": int(rerun), "note": txt})

    # 1-2: PD moved, rating unchanged (corporate), planted in the prior run's PD
    same_rating = (cur_i.rating == pri_i.rating.reindex(cur_i.index)) & (cur_i.book == "corporate") & (cur_i.stage == 1) \
        & (cur_i.ead_sar_mn > 5)
    for k in range(2):
        i = pick(same_rating, k)
        old = float(cur_i.at[i, "pd_12m_pct"]) / 3.2
        pri_i.at[i, "pd_12m_pct"] = old
        note(i, RUN_CURRENT, "PD changed with no rating change", "pd_12m_pct", round(old, 4),
             round(float(cur_i.at[i, "pd_12m_pct"]), 4), "PD within ±10% of prior while rating unchanged", True,
             f"PD up {cur_i.at[i, 'pd_12m_pct'] / old:.1f}x quarter on quarter; rating {cur_i.at[i, 'rating']} both runs")
    # 3: LGD moved, collateral unchanged (corporate secured)
    sec = (cur_i.book == "corporate") & cur_i.collateral_sar_mn.notna() & (cur_i.lgd_pct > 35) & (cur_i.ead_sar_mn > 3)
    i = pick(sec)
    pri_i.at[i, "lgd_pct"] = float(cur_i.at[i, "lgd_pct"]) - 22.0
    pri_i.at[i, "collateral_sar_mn"] = cur_i.at[i, "collateral_sar_mn"]
    note(i, RUN_CURRENT, "LGD changed with no collateral change", "lgd_pct", round(pri_i.at[i, "lgd_pct"], 3),
         round(float(cur_i.at[i, "lgd_pct"]), 3), "LGD unchanged when collateral value unchanged", True,
         "LGD up 22 points; collateral value identical in both runs")
    # 4: LGD moved, collateral unchanged (retail mortgage)
    mort = (cur_i.book == "retail") & (cur_i.sector == "Auto Finance") & cur_i.collateral_sar_mn.notna() \
        & (cur_i.lgd_pct > 25)
    i = pick(mort)
    pri_i.at[i, "lgd_pct"] = float(cur_i.at[i, "lgd_pct"]) - 12.0
    pri_i.at[i, "collateral_sar_mn"] = cur_i.at[i, "collateral_sar_mn"]
    note(i, RUN_CURRENT, "LGD changed with no collateral change", "lgd_pct", round(pri_i.at[i, "lgd_pct"], 3),
         round(float(cur_i.at[i, "lgd_pct"]), 3), "LGD unchanged when collateral value unchanged", True,
         "Auto finance LGD up 12 points; vehicle value identical in both runs")
    # 5: PD moved, score band unchanged (retail)
    rb = (cur_i.book == "retail") & (cur_i.rating == pri_i.rating.reindex(cur_i.index)) & (cur_i.stage == 1)
    i = pick(rb)
    old = float(cur_i.at[i, "pd_12m_pct"]) / 2.5
    pri_i.at[i, "pd_12m_pct"] = old
    note(i, RUN_CURRENT, "PD changed with no rating change", "pd_12m_pct", round(old, 4),
         round(float(cur_i.at[i, "pd_12m_pct"]), 4), "PD within ±10% of prior while score band unchanged", True,
         f"PD up 2.5x month on month; score band {cur_i.at[i, 'rating']} both runs")
    # 6: EAD above the limit fed to the engine (stale limit feed; book limit unchanged)
    big = (cur_i.book == "corporate") & (cur_i.ead_sar_mn > 10) & (cur_i.stage == 1)
    i = pick(big)
    fed = round(float(cur_i.at[i, "ead_sar_mn"]) * 0.82, 4)
    note(i, RUN_CURRENT, "EAD greater than limit", "limit_sar_mn", round(float(pri_i.at[i, "limit_sar_mn"]), 4), fed,
         "EAD ≤ limit", False, "Limit feed to the engine is stale (82% of EAD); book limit is correct, ECL unaffected")
    cur_i.at[i, "limit_sar_mn"] = fed
    # 7: stage inconsistent with DPD (DPD feed says 47, stage 1)
    s1 = (cur_i.book == "corporate") & (cur_i.stage == 1) & (cur_i.dpd_days == 0) & (cur_i.ead_sar_mn > 2)
    i = pick(s1)
    note(i, RUN_CURRENT, "Stage inconsistent with DPD", "dpd_days", int(pri_i.at[i, "dpd_days"]), 47, "Stage 2 at DPD > 30",
         True, "DPD feed to the engine shows 47 days while the facility is Stage 1 (CBUAE Art 7.8)")
    cur_i.at[i, "dpd_days"] = 47
    # 8: missing collateral value on a secured facility
    sec2 = (cur_i.book == "corporate") & cur_i.collateral_sar_mn.notna() & (cur_i.ead_sar_mn > 4)
    i = pick(sec2, 1)
    note(i, RUN_CURRENT, "Missing collateral value", "collateral_sar_mn", round(float(pri_i.at[i, "collateral_sar_mn"] or 0), 4),
         None, "Collateral value present for a secured facility", True,
         "Collateral value blank in the engine input; a rerun would treat the facility as unsecured")
    cur_i.at[i, "collateral_sar_mn"] = np.nan
    # 9: Stage 3 with zero ECL in the prior run (comparatives wrong)
    s3 = (cur_i.book == "corporate") & (cur_i.stage == 3) & (pri_i.stage.reindex(cur_i.index) == 3)
    i = pick(s3)
    old = float(pri_i.at[i, "ecl_sar_mn"])
    for c in ("ecl_base_sar_mn", "ecl_upside_sar_mn", "ecl_downside_sar_mn", "ecl_weighted_sar_mn", "overlay_sar_mn",
              "ecl_sar_mn"):
        pri_i.at[i, c] = 0.0
    note(i, RUN_PRIOR, "Stage 3 with zero ECL", "ecl_sar_mn", 0.0, round(float(cur_i.at[i, "ecl_sar_mn"]), 4),
         "ECL > 0 for Stage 3", True,
         f"Prior run carried zero ECL on a Stage 3 facility (book had {old:.4f}); quarter-on-quarter ECL movement overstated")
    out = pd.concat([pri_i.reset_index(), cur_i.reset_index()], ignore_index=True)[_RUN_COLS]
    for c in ("ecl_base_sar_mn", "ecl_upside_sar_mn", "ecl_downside_sar_mn", "ecl_weighted_sar_mn", "overlay_sar_mn"):
        out[c] = out[c].astype(float).round(8)   # derived; the book fields are carried unrounded
    out = out.sort_values(["run_id", "exposure_id"]).reset_index(drop=True)
    anom = pd.DataFrame(an)
    for c in ("prior_value", "current_value"):
        anom[c] = anom[c].map(lambda v: None if v is None or pd.isna(v) else str(v))
    return {"ecl_facility": out, "ecl_anomaly": anom}


