def relationships(d: dict, dep_cp: pd.DataFrame) -> dict[str, pd.DataFrame]:
    rng = _rng(7)
    B, RG, PR, ED = d["B"], d["RG"], d["PR"], d["ED"]
    names = B.set_index("borrower_id").borrower_name
    nodes = [pd.DataFrame({"node_id": B.borrower_id, "node_type": "obligor", "name": B.borrower_name,
                           "cif": B.borrower_id, "book": "corporate"})]
    g = RG[["group_id", "group_name"]].drop_duplicates("group_id")
    nodes.append(pd.DataFrame({"node_id": g.group_id, "node_type": "group", "name": g.group_name, "cif": None,
                               "book": "corporate"}))
    links = [pd.DataFrame({"src_id": RG.group_id, "dst_id": RG.borrower_id, "link_type": "group_member",
                           "share_pct": RG.ownership_pct, "nominee_flag": 0, "amount_sar_mn": np.nan,
                           "source": "group register"})]
    gu = ED[ED.rel_type == "GUARANTEES"]
    links.append(pd.DataFrame({"src_id": gu.source_borrower_id, "dst_id": gu.target_borrower_id, "link_type": "guarantor",
                               "share_pct": np.nan, "nominee_flag": 0, "amount_sar_mn": gu.guarantee_amount_sar_mn,
                               "source": "guarantee register"}))
    # shareholders / sponsors (persons from the relationship domain), with nominee flags
    live = PR[PR.valid_to_quarter.isna()]
    sh = live[live.role.astype(str).str.contains("Share|Owner|Sponsor|Partner", case=False)]
    other = live[~live.index.isin(sh.index)]
    pn = live.drop_duplicates("person_id")
    nodes.append(pd.DataFrame({"node_id": pn.person_id, "node_type": "person", "name": pn.person_name, "cif": None,
                               "book": "corporate"}))
    nom = (rng.random(len(sh)) < 0.07).astype(int)
    links.append(pd.DataFrame({"src_id": sh.person_id, "dst_id": sh.borrower_id,
                               "link_type": np.where(sh.ownership_pct.fillna(0) >= 50, "sponsor", "shareholder"),
                               "share_pct": sh.ownership_pct, "nominee_flag": nom, "amount_sar_mn": np.nan,
                               "source": "KYC ownership"}))
    links.append(pd.DataFrame({"src_id": other.person_id, "dst_id": other.borrower_id,
                               "link_type": "officer:" + other.role.astype(str), "share_pct": other.ownership_pct,
                               "nominee_flag": 0, "amount_sar_mn": np.nan, "source": "KYC officers"}))
    st = d["staff"]
    nodes.append(pd.DataFrame({"node_id": st.person_id, "node_type": "person", "name": st.person_name, "cif": None,
                               "book": "corporate"}))
    links.append(pd.DataFrame({"src_id": st.person_id, "dst_id": st.obligor_id, "link_type": "staff_link",
                               "share_pct": st.share_pct, "nominee_flag": 0, "amount_sar_mn": np.nan,
                               "source": "staff declarations"}))
    # counterparty edges from deposits (12-month totals, internal counterparties only)
    cpi = dep_cp.dropna(subset=["counterparty_cif"]).groupby(["obligor_id", "counterparty_cif", "direction", "category"]) \
        .amount_sar_mn.sum().reset_index()
    links.append(pd.DataFrame({"src_id": np.where(cpi.direction == "in", cpi.counterparty_cif, cpi.obligor_id),
                               "dst_id": np.where(cpi.direction == "in", cpi.obligor_id, cpi.counterparty_cif),
                               "link_type": "counterparty", "share_pct": np.nan, "nominee_flag": 0,
                               "amount_sar_mn": cpi.amount_sar_mn.round(4),
                               "source": "deposits: " + cpi.category}))
    rel_node = pd.concat(nodes, ignore_index=True).drop_duplicates("node_id").sort_values("node_id").reset_index(drop=True)
    rel_link = pd.concat(links, ignore_index=True)
    rel_link = rel_link.sort_values(["src_id", "dst_id", "link_type"]).reset_index(drop=True)
    rel_link.insert(0, "link_id", [f"LK{i + 1:07d}" for i in range(len(rel_link))])
    del names
    return {"rel_node": rel_node, "rel_link": rel_link}


