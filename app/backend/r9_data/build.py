def _rng(k: int) -> np.random.Generator:
    return np.random.default_rng([SEED, k])


def _q_end_month(q: str) -> str:
    return f"{q[:4]}-{int(q[-1]) * 3:02d}"


def _months(end: str, n: int) -> list[str]:
    p = pd.Period(end, "M")
    return [str(p - i) for i in range(n - 1, -1, -1)]


def _add_months(ym: str, n: int) -> str:
    return str(pd.Period(ym, "M") + n)


def _crm_clauses() -> dict[str, str]:
    d = json.loads(CRM_JSON.read_text())
    return {c["number"]: c["clause"] for c in d["clauses"]}


# ----------------------------------------------------------------------------- inputs
def load_books() -> dict:
    cb, rb = book("corporate"), book("retail")
    cq, cp = cb.as_of, cb.comparison
    rm, rp = rb.as_of, rb.comparison
    fac = pd.read_parquet(cb.path("corp_facility_quarter"))
    F = fac[fac.reporting_quarter == cq].sort_values("facility_id").reset_index(drop=True)
    Fp = fac[fac.reporting_quarter == cp].sort_values("facility_id").reset_index(drop=True)
    bor = pd.read_parquet(cb.path("corp_borrower_quarter"))
    B = bor[bor.reporting_quarter == cq].sort_values("borrower_id").reset_index(drop=True)
    Bp = bor[bor.reporting_quarter == cp].sort_values("borrower_id").reset_index(drop=True)
    col = pd.read_parquet(cb.path("corp_collateral_quarter"))
    COL = col[col.reporting_quarter == cq].sort_values("collateral_id").reset_index(drop=True)
    COLp = col[col.reporting_quarter == cp].sort_values("collateral_id").reset_index(drop=True)
    cov = pd.read_parquet(cb.path("corp_covenant_quarter"))
    CV = cov[cov.reporting_quarter == cq].sort_values("covenant_id").reset_index(drop=True)
    acc = pd.read_parquet(rb.path("retail_account_month"))
    A = acc[acc.reporting_month == rm].sort_values("account_id").reset_index(drop=True)
    Ap = acc[acc.reporting_month == rp].sort_values("account_id").reset_index(drop=True)
    cus = pd.read_parquet(rb.path("retail_customer_month"))
    C = cus[cus.reporting_month == rm].sort_values("customer_id").reset_index(drop=True)
    rcol = pd.read_parquet(rb.path("retail_collateral_month"))
    RCOL = rcol[rcol.reporting_month == rm].sort_values("account_id").reset_index(drop=True)
    RCOLp = rcol[rcol.reporting_month == rp].sort_values("account_id").reset_index(drop=True)
    ews_c = pd.read_parquet(EWS_CORP, columns=["facility_id", "reporting_quarter", "ews_band", "ews_reasons"])
    ews_c = ews_c[ews_c.reporting_quarter == cq].set_index("facility_id")
    ews_r = pd.read_parquet(EWS_RET, columns=["account_id", "reporting_month", "ews_band", "ews_reasons"])
    ews_r = ews_r[ews_r.reporting_month == rm].set_index("account_id")
    rg = pd.read_parquet(REL_DIR / "rel_group_quarter.parquet")
    RG = rg[rg.reporting_quarter == cq].sort_values(["group_id", "borrower_id"]).reset_index(drop=True)
    pr = pd.read_parquet(REL_DIR / "rel_person_role.parquet").sort_values(["person_id", "borrower_id"])
    ed = pd.read_parquet(REL_DIR / "rel_edge_quarter.parquet")
    ED = ed[ed.reporting_quarter == cq].sort_values("edge_id").reset_index(drop=True)
    return dict(cq=cq, cp=cp, rm=rm, rp=rp, F=F, Fp=Fp, B=B, Bp=Bp, COL=COL, COLp=COLp, CV=CV, A=A, Ap=Ap, C=C,
                RCOL=RCOL, RCOLp=RCOLp, ews_c=ews_c, ews_r=ews_r, RG=RG, PR=pr.reset_index(drop=True), ED=ED)


