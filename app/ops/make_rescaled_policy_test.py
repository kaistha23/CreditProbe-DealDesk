"""Generate v5 copies of the frozen policy tests at the rescaled limits.

Three frozen test files write the credit-policy limits into their assertions
and scripted answers: CP-1.1 "SAR 25,000 million" and CP-1.2 "50000". In v5
both limits moved with the book, x0.01 (SAR 250m and 500m;
docs/v5/RESCALE.md), so the tests that quote the old figures are declared
exceptions in ops/gate.py. This writes the SAME tests with the figures moved
to the v5 limits, so every behaviour they prove (the limit is retrieved by
clause, attached to the prompt, receipted, and a limit quoted without its
clause is refused and re-asked) is still proven at v5's limits -- not merely
excused.

The frozen originals are never edited. tests/v5/test_sync_books.py checks
each copy is exactly this transformation of its original. Every substituted
token was checked to be a limit literal and nothing else.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "tests" / "cockpit_v4"

COPIES = (
    ("test_misread_as_product_help.py", "test_v5_rescaled_policy_guard.py",
     (("25,000", "250"), ("25000", "250"))),
    ("test_credit_policy.py", "test_v5_rescaled_credit_policy.py",
     (("50000", "500"),)),
    ("test_live_uat_matrix_revision.py", "test_v5_rescaled_live_uat_matrix.py",
     (("25,000", "250"), ("25000", "250"))),
)


def render(source: str, substitutions) -> str:
    text = (T / source).read_text(encoding="utf-8")
    for before, after in substitutions:
        text = text.replace(before, after)
    header = (f"# GENERATED by ops/make_rescaled_policy_test.py from {source}\n"
              "# with the credit-policy limits at their v5 values (x0.01). Do not edit; regenerate.\n")
    return header + text


if __name__ == "__main__":
    for source, target, subs in COPIES:
        (T / target).write_text(render(source, subs), encoding="utf-8")
        print("wrote", (T / target).relative_to(ROOT))
